-- Vol 1, Chapter 7: Invoicing
-- Built up one figure at a time; each section is headed by the figure it implements.
-- Figs 7.1b and 7.3b (alternates) are not built: 7.1a and 7.2-7.3a hold them,
-- with their rules as data-quality queries (NOTES).

-- ============================================================
-- Fig 7.1a — Invoice and invoice items
-- ============================================================
-- One INVOICE for both directions. SALES and PURCHASE INVOICE have no
-- attributes or lines of their own while 7.3b isn't built, so they become an
-- invoice_kind discriminator (as Ch 4's order_kind).

create table invoice (
  invoice_id   integer generated by default as identity primary key,
  invoice_kind text not null check (invoice_kind in ('SALES', 'PURCHASE')),
  invoice_date date not null,
  message      text,   -- a note to the customer printed on the bill
  description  text    -- what the invoice is about
);

-- INVOICE ITEM TYPE holds 7.1b's two subtype sets as its top rows:
-- ACQUIRING_ITEM (what the party actually got) and ADJUSTMENT (tax, fees,
-- discounts...), the leaves under them (NOTES, point 1). Only leaves are
-- used on items: a data-quality query.
create table invoice_item_type (
  invoice_item_type_id text primary key,
  parent_type_id       text references invoice_item_type,
  description          text not null
);

-- An item is identified by its invoice plus a sequence number (the tilde on
-- "part of"). We keep a surrogate key; the seq's uniqueness within the
-- invoice is a data-quality query.
--
-- What a line bills is a product, a feature or a serialized inventory item,
-- or only its description (a one-off). Quantity is optional (a fee or a
-- feature has only an amount) and may be negative: a correction credits -2
-- of a line billed 10. amount is per unit when there is a quantity, else the
-- line's whole value (point 2), and is always positive: a DISCOUNT's type
-- lowers the total.
--
-- Two recursive lines: "adjusted by" ties an adjustment or a correction to
-- the line it changes; "sold with" ties a feature line to its product line.
create table invoice_item (
  invoice_item_id                integer generated by default as identity primary key,
  invoice_id                     integer not null references invoice,             -- "part of"
  invoice_item_seq_id            integer not null,                                -- the line number within the invoice
  invoice_item_type_id           text    not null references invoice_item_type,   -- "described by"
  product_id                     integer references product,                      -- "the charge for"
  product_feature_id             integer references product_feature,              -- "the charge for"
  inventory_item_id              integer references inventory_item,               -- "the charge for" (a serialized item)
  adjustment_for_invoice_item_id integer references invoice_item,                 -- "the adjustment for"
  sold_with_invoice_item_id      integer references invoice_item,                 -- "sold with"
  taxable_flag                   boolean not null,
  quantity                       numeric check (quantity <> 0),
  amount                         numeric check (amount >= 0),
  item_description               text,
  check (adjustment_for_invoice_item_id <> invoice_item_id),
  check (sold_with_invoice_item_id <> invoice_item_id)
);

-- ============================================================
-- Fig 7.2 — Invoice parties
-- ============================================================
-- The two key parties are lines to PARTY (not PARTY ROLE: that's 7.3b).
-- Billed from is mandatory. Billed to is drawn mandatory too, but 7.3a puts
-- it in an arc with the billing account, so it's nullable and the arc's
-- check constraint (7.3a) makes it exactly one.
--
-- Where the bill went and came from: any contact mechanism (an e-mail is as
-- good as a street). That the billed party uses it for billing is a
-- data-quality query, the book's own example rule.
alter table invoice
  add column billed_to_party_id                integer references party,               -- "billed to"
  add column billed_from_party_id              integer not null references party,      -- "billed from"
  add column addressed_to_contact_mechanism_id integer references contact_mechanism,   -- "addressed to"
  add column sent_from_contact_mechanism_id    integer references contact_mechanism;   -- "sent from"

-- INVOICE ROLE: anyone else on an invoice (who keyed it in, who approved
-- it), with when they did it. Identified by invoice + party + type (tildes on
-- all three): a data-quality query beside the surrogate key.
--
-- INVOICE ROLE TYPE is a lookup of its own, like the other role types (NOTES,
-- point 8; Ch 2's TODO on a shared ROLE TYPE).
create table invoice_role_type (
  invoice_role_type_id text primary key,
  description          text not null
);

create table invoice_role (
  invoice_role_id      integer generated by default as identity primary key,
  invoice_id           integer     not null references invoice,             -- "for"
  party_id             integer     not null references party,               -- "of"
  invoice_role_type_id text        not null references invoice_role_type,   -- "described by"
  role_datetime        timestamptz not null,                                -- when the party played the role
  percentage           numeric check (percentage between 0 and 100)
);

-- ============================================================
-- Fig 7.3a — Billing account
-- ============================================================
-- An invoice can go to an account instead of a party. The account says
-- where its bills go ("billed at", mandatory: every bill ends up somewhere)
-- and, through its dated roles, who pays.

create table billing_account (
  billing_account_id             integer generated by default as identity primary key,
  from_date                      date    not null,
  thru_date                      date,
  description                    text,
  billed_at_contact_mechanism_id integer not null references contact_mechanism,   -- "billed at"
  check (thru_date is null or thru_date > from_date)
);

create table billing_account_role_type (
  billing_account_role_type_id text primary key,
  description                  text not null
);

-- Identified by account + party + type in the book; the dates let a party
-- leave and come back, so the duplicate check adds the from date (point 10).
create table billing_account_role (
  billing_account_role_id      integer generated by default as identity primary key,
  billing_account_id           integer not null references billing_account,             -- "for"
  party_id                     integer not null references party,                       -- "an account for"
  billing_account_role_type_id text    not null references billing_account_role_type,   -- "described by"
  from_date                    date    not null,
  thru_date                    date,
  check (thru_date is null or thru_date > from_date)
);

-- The arc: billed to a party or to an account, exactly one. One row, one
-- rule, so a check constraint.
alter table invoice
  add column billing_account_id integer references billing_account,   -- "billed to" (the account)
  add constraint invoice_billed_to_arc check (num_nonnulls(billed_to_party_id, billing_account_id) = 1);

-- Ch 4's orders: "with a requested bill to" an account, in an arc with the
-- bill-to role (the book's note on Figs 4.3 and 4.5). Both stay optional, so
-- at most one.
alter table sales_order
  add column bill_to_billing_account_id integer references billing_account,   -- "with a requested bill to"
  add constraint sales_order_bill_to_arc check (num_nonnulls(bill_to_party_role_id, bill_to_billing_account_id) <= 1);

alter table purchase_order
  add column bill_to_billing_account_id integer references billing_account,   -- "with a requested bill to"
  add constraint purchase_order_bill_to_arc check (num_nonnulls(bill_to_party_role_id, bill_to_billing_account_id) <= 1);

-- ============================================================
-- Fig 7.4 — Invoice status and terms
-- ============================================================
-- INVOICE STATUS: a history of events, as Ch 4's order status and Ch 5's
-- shipment status. The types are rows of Ch 2's status_type under an
-- INVOICE_STATUS group (a check). Identified by invoice + type + date (the
-- tildes): surrogate key, the identifier a check. The current status is the
-- latest one. No PAID status: payments (7.8a) say that (NOTES, point 22).
create table invoice_status (
  invoice_status_id integer generated by default as identity primary key,
  invoice_id        integer not null references invoice,       -- "a status for"
  status_type_id    text    not null references status_type,   -- "described by"
  status_date       date    not null
);

-- INVOICE TERM: on the whole invoice or on one line, never both (the arc,
-- drawn this time: one row, one rule, a check constraint). TERM TYPE is Ch
-- 4's shared list. The value is a bare number whose meaning comes from the
-- type; some types need none (point 13).
create table invoice_term (
  invoice_term_id integer generated by default as identity primary key,
  term_type_id    text    not null references term_type,   -- "described by"
  invoice_id      integer references invoice,              -- "a condition for" the whole invoice
  invoice_item_id integer references invoice_item,         -- "a condition for" one line
  term_value      numeric,
  constraint invoice_term_arc check (num_nonnulls(invoice_id, invoice_item_id) = 1)
);

-- ============================================================
-- Fig 7.5 — Billing for shipment items
-- ============================================================
-- Which shipment lines (Ch 5) an invoice line charges for. Many to many:
-- one invoice line can gather several shipment lines, and one shipment line
-- can be billed again (a credit on a later bill). No attributes: each link
-- bills the shipment line whole. Identified by its two lines (the tildes):
-- surrogate key, the pair twice a check.
create table shipment_item_billing (
  shipment_item_billing_id integer generated by default as identity primary key,
  shipment_item_id         integer not null references shipment_item,   -- "of"
  invoice_item_id          integer not null references invoice_item     -- "for"
);

-- ============================================================
-- Fig 7.6 — Billing of time entries and work efforts
-- ============================================================
-- Two ways to bill services (Ch 6): by the hour, each time entry on the line
-- that charges for it; or by the job, a work effort (or a share of it, a
-- milestone) on the line. Both many to many, identified by their two lines
-- (tildes): surrogate keys, the pairs twice a check. The book's optional
-- hours on TIME ENTRY BILLING isn't drawn and isn't built (point 15).
create table time_entry_billing (
  time_entry_billing_id integer generated by default as identity primary key,
  time_entry_id         integer not null references time_entry,     -- "of"
  invoice_item_id       integer not null references invoice_item    -- "for"
);

create table work_effort_billing (
  work_effort_billing_id integer generated by default as identity primary key,
  work_effort_id         integer not null references work_effort,    -- "of"
  invoice_item_id        integer not null references invoice_item,   -- "for"
  percentage             numeric check (percentage > 0 and percentage <= 100)   -- the share of the effort this line bills
);

-- ============================================================
-- Fig 7.7 — Billing for order items
-- ============================================================
-- For businesses that bill the order rather than what shipped: how much of
-- an order line (Ch 4) an invoice line bills. Many to many, with a quantity
-- and an amount, so an order line can be billed in parts and an invoice line
-- can gather several orders. Identified by its two lines (tildes): surrogate
-- key. Billing a line through both its order and its shipment would count it
-- twice: a check (NOTES, point 17).
create table order_item_billing (
  order_item_billing_id integer generated by default as identity primary key,
  order_item_id         integer not null references order_item,     -- "of"
  invoice_item_id       integer not null references invoice_item,   -- "for"
  quantity              numeric check (quantity <> 0),               -- how much of the order line this bills
  amount                numeric                                      -- what that part comes to (USD)
);

-- ============================================================
-- Fig 7.8a — Invoice payments
-- ============================================================
-- Fig 7.8b (alternate) is not built: 7.10 keeps 7.8a's application to the
-- whole invoice (NOTES, point 19).
--
-- PAYMENT: money from one party to another. RECEIPT and DISBURSEMENT have no
-- attributes, so a payment_kind discriminator: a receipt comes in to one of
-- our internal organizations, a disbursement goes out from one (checks).
create table payment_method_type (
  payment_method_type_id text primary key,
  description            text not null
);

create table payment (
  payment_id             integer generated by default as identity primary key,
  payment_kind           text    not null check (payment_kind in ('RECEIPT', 'DISBURSEMENT')),
  payment_method_type_id text    not null references payment_method_type,   -- "paid via"
  from_party_id          integer not null references party,                 -- "from": the payor
  to_party_id            integer not null references party,                 -- "to": the receiver
  effective_date         date    not null,
  payment_ref_num        text    not null,   -- the check number or the transfer's reference
  amount                 numeric not null check (amount > 0),   -- USD
  comment                text,
  check (from_party_id <> to_party_id)
);

-- PAYMENT APPLICATION: how much of a payment went to which invoice, or "on
-- account" to a billing account with no invoice. Exactly one of the two
-- (point 18): one row, one rule, a check constraint. Many to many between
-- payments and invoices: partial payments, one payment for several bills.
create table payment_application (
  payment_application_id integer generated by default as identity primary key,
  payment_id             integer not null references payment,   -- "applying"
  invoice_id             integer references invoice,            -- "applied to" an invoice
  billing_account_id     integer references billing_account,    -- "applied to" an account, on account
  amount_applied         numeric not null check (amount_applied > 0),
  constraint payment_application_arc check (num_nonnulls(invoice_id, billing_account_id) = 1)
);

-- What each invoice comes to, as 7.1a's totals query reckons it (discounts
-- lower it): nothing stores a balance, so outstanding amounts are computed
-- from this and the applications.
create view invoice_total as
select v.invoice_id,
       coalesce(sum(case when i.invoice_item_type_id = 'DISCOUNT' then -1 else 1 end * coalesce(i.quantity, 1) * i.amount), 0) as total_due
from invoice v
left join invoice_item i on i.invoice_id = v.invoice_id
group by v.invoice_id;

-- ============================================================
-- Fig 7.9 — Financial accounts, withdrawals and deposits
-- ============================================================
-- FINANCIAL ACCOUNT: where money sits (a bank or an investment account).
-- The subtypes have no attributes, so a kind discriminator; the optional
-- FINANCIAL ACCOUNT TYPE (checking, savings, IRA, mutual fund) is a
-- hierarchy whose top rows are the two kinds, and a type must sit under the
-- account's kind (a check). The key takes the bank's number, so a bigint
-- (point 26).
create table financial_account_type (
  financial_account_type_id text primary key,
  parent_type_id            text references financial_account_type,
  description               text not null
);

create table financial_account (
  financial_account_id      bigint  primary key,
  financial_account_kind    text    not null check (financial_account_kind in ('BANK', 'INVESTMENT')),
  financial_account_type_id text    references financial_account_type,   -- "described by"
  financial_account_name    text    not null
);

-- Who holds the account and how (owner, signer), dated. Identified by
-- account + type + party (tildes): surrogate key, the duplicate a check.
create table financial_account_role_type (
  financial_account_role_type_id text primary key,
  description                    text not null
);

create table financial_account_role (
  financial_account_role_id      integer generated by default as identity primary key,
  financial_account_id           bigint  not null references financial_account,             -- "of"
  party_id                       integer not null references party,                         -- "for"
  financial_account_role_type_id text    not null references financial_account_role_type,   -- "for"
  from_date                      date    not null,
  thru_date                      date,
  check (thru_date is null or thru_date > from_date)
);

-- FINANCIAL ACCOUNT TRANSACTION: what actually moved in the account. The
-- three subtypes have no attributes: a kind. A deposit's or withdrawal's
-- amount is the sum of its payments; an adjustment (a fee, interest) has no
-- payment behind it, so only it carries an amount, signed (point 24).
create table financial_account_transaction (
  financial_account_transaction_id integer generated by default as identity primary key,
  transaction_kind                 text    not null check (transaction_kind in ('DEPOSIT', 'WITHDRAWAL', 'ADJUSTMENT')),
  financial_account_id             bigint  not null references financial_account,   -- "affecting"
  executed_by_party_id             integer not null references party,               -- "executed by"
  transaction_date                 date    not null,
  entry_date                       date,
  amount                           numeric,   -- adjustments only
  constraint financial_account_transaction_amount check ((transaction_kind = 'ADJUSTMENT') = (amount is not null))
);

-- A receipt is "deposited via" a deposit, many to one; a disbursement is
-- "affecting" one withdrawal (7.10 draws one line, many payments to one
-- transaction). One FK; which kind of payment goes in which kind of
-- transaction, and one check per withdrawal, are checks (point 27).
alter table payment
  add column financial_account_transaction_id integer references financial_account_transaction;   -- "deposited via" / "affecting"
