-- Vol 1, Chapter 7: Invoicing
-- Built up one figure at a time; each section is headed by the figure it implements.
-- Figs 7.1b and 7.3b (alternates) are not built: 7.1a and 7.2-7.3a hold them,
-- with their rules as data-quality queries (NOTES).

-- ============================================================
-- Fig 7.1a — Invoice and invoice items
-- ============================================================
-- One INVOICE for both directions. SALES and PURCHASE INVOICE have no
-- attributes or lines of their own while 7.3b isn't built, so they become an
-- invoice_kind discriminator (as Ch 4's order_kind).

create table invoice (
  invoice_id   integer generated by default as identity primary key,
  invoice_kind text not null check (invoice_kind in ('SALES', 'PURCHASE')),
  invoice_date date not null,
  message      text,   -- a note to the customer printed on the bill
  description  text    -- what the invoice is about
);

-- INVOICE ITEM TYPE holds 7.1b's two subtype sets as its top rows:
-- ACQUIRING_ITEM (what the party actually got) and ADJUSTMENT (tax, fees,
-- discounts...), the leaves under them (NOTES, point 1). Only leaves are
-- used on items: a data-quality query.
create table invoice_item_type (
  invoice_item_type_id text primary key,
  parent_type_id       text references invoice_item_type,
  description          text not null
);

-- An item is identified by its invoice plus a sequence number (the tilde on
-- "part of"). We keep a surrogate key; the seq's uniqueness within the
-- invoice is a data-quality query.
--
-- What a line bills is a product, a feature or a serialized inventory item,
-- or only its description (a one-off). Quantity is optional (a fee or a
-- feature has only an amount) and may be negative: a correction credits -2
-- of a line billed 10. amount is per unit when there is a quantity, else the
-- line's whole value (point 2), and is always positive: a DISCOUNT's type
-- lowers the total.
--
-- Two recursive lines: "adjusted by" ties an adjustment or a correction to
-- the line it changes; "sold with" ties a feature line to its product line.
create table invoice_item (
  invoice_item_id                integer generated by default as identity primary key,
  invoice_id                     integer not null references invoice,             -- "part of"
  invoice_item_seq_id            integer not null,                                -- the line number within the invoice
  invoice_item_type_id           text    not null references invoice_item_type,   -- "described by"
  product_id                     integer references product,                      -- "the charge for"
  product_feature_id             integer references product_feature,              -- "the charge for"
  inventory_item_id              integer references inventory_item,               -- "the charge for" (a serialized item)
  adjustment_for_invoice_item_id integer references invoice_item,                 -- "the adjustment for"
  sold_with_invoice_item_id      integer references invoice_item,                 -- "sold with"
  taxable_flag                   boolean not null,
  quantity                       numeric check (quantity <> 0),
  amount                         numeric check (amount >= 0),
  item_description               text,
  check (adjustment_for_invoice_item_id <> invoice_item_id),
  check (sold_with_invoice_item_id <> invoice_item_id)
);

-- ============================================================
-- Fig 7.2 — Invoice parties
-- ============================================================
-- The two key parties are lines to PARTY (not PARTY ROLE: that's 7.3b).
-- Billed from is mandatory. Billed to is drawn mandatory too, but 7.3a puts
-- it in an arc with the billing account, so it's nullable and the arc's
-- check constraint (7.3a) makes it exactly one.
--
-- Where the bill went and came from: any contact mechanism (an e-mail is as
-- good as a street). That the billed party uses it for billing is a
-- data-quality query, the book's own example rule.
alter table invoice
  add column billed_to_party_id                integer references party,               -- "billed to"
  add column billed_from_party_id              integer not null references party,      -- "billed from"
  add column addressed_to_contact_mechanism_id integer references contact_mechanism,   -- "addressed to"
  add column sent_from_contact_mechanism_id    integer references contact_mechanism;   -- "sent from"

-- INVOICE ROLE: anyone else on an invoice (who keyed it in, who approved
-- it), with when they did it. Identified by invoice + party + type (tildes on
-- all three): a data-quality query beside the surrogate key.
--
-- INVOICE ROLE TYPE is a lookup of its own, like the other role types (NOTES,
-- point 8; Ch 2's TODO on a shared ROLE TYPE).
create table invoice_role_type (
  invoice_role_type_id text primary key,
  description          text not null
);

create table invoice_role (
  invoice_role_id      integer generated by default as identity primary key,
  invoice_id           integer     not null references invoice,             -- "for"
  party_id             integer     not null references party,               -- "of"
  invoice_role_type_id text        not null references invoice_role_type,   -- "described by"
  role_datetime        timestamptz not null,                                -- when the party played the role
  percentage           numeric check (percentage between 0 and 100)
);
