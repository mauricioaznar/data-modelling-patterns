-- Vol 1, Chapter 6: Work Effort
-- Built up one figure at a time; each section is headed by the figure it implements.

-- ============================================================
-- Fig 6.1 — Work requirement
-- ============================================================
-- Ch 4's REQUIREMENT gets a type, and its WORK subtype gets a table. The
-- type is a hierarchy: PRODUCT_REQUIREMENT and WORK_REQUIREMENT group the
-- leaves, so a type's group must agree with requirement_kind (a check,
-- NOTES point 2). Drawn mandatory, built nullable: Ch 4's product
-- requirements have no type yet (point 1).
create table requirement_type (
  requirement_type_id text primary key,
  parent_type_id      text references requirement_type,
  description         text not null
);

alter table requirement
  add column requirement_type_id text references requirement_type;   -- "described by"

-- FIXED ASSET (Ch 5's) gets the attributes drawn here. date_acquired is
-- drawn mandatory: Ch 5's assets are dated in the seed, and a check catches
-- one that isn't.
alter table fixed_asset
  add column date_acquired       date,
  add column date_last_serviced  date,
  add column date_next_service   date,
  add column production_capacity numeric check (production_capacity >= 0),
  add check (date_next_service is null or date_last_serviced is null
             or date_next_service >= date_last_serviced);

create table deliverable_type (
  deliverable_type_id text primary key,
  description         text not null
);

create table deliverable (
  deliverable_id      integer generated by default as identity primary key,
  deliverable_type_id text not null references deliverable_type,   -- "defined by"
  name                text not null,
  description         text
);

-- WORK REQUIREMENT, a subtype table sharing the requirement's key (as Ch 4's
-- product_requirement). All three lines are optional: which one is expected
-- depends on the type, and queries check it (a production run names a
-- product, a repair a machine).
create table work_requirement (
  requirement_id integer primary key references requirement,
  product_id     integer references product,       -- "produce"
  fixed_asset_id integer references fixed_asset,   -- "related to"
  deliverable_id integer references deliverable    -- "for work to produce"
);

-- ============================================================
-- Fig 6.2 — Work requirement roles
-- ============================================================
-- Ch 4's REQUIREMENT ROLE, redrawn with a comment. The book's identifier
-- (requirement, party, role type, from date) is a data-quality query beside
-- the surrogate key; so is one responsible party at a time (our reading of
-- Table 6.3). The new role types are rows of Ch 4's requirement_role_type.
alter table requirement_role
  add column comment text;

-- ============================================================
-- Fig 6.3a — Work effort generation
-- ============================================================
-- Ch 2's WORK EFFORT gets the rest of its attributes, a place and a purpose.
-- Two subtype sets, each a lookup: the level of the work (Ch 2's
-- work_effort_type: program, project, phase, task, activity) and its purpose
-- (production run, maintenance, workflow, research). Purpose is built
-- optional (NOTES, point 6). Only PRODUCTION RUN has attributes, so only it
-- gets a subtype table; a check keeps it in step with the purpose.
alter table work_effort_type
  add column standard_work_hours numeric check (standard_work_hours >= 0);

create table work_effort_purpose_type (
  work_effort_purpose_type_id text primary key,
  description                 text not null
);

alter table work_effort
  add column actual_start_datetime       timestamptz,
  add column actual_completion_datetime  timestamptz,
  add column actual_hours                numeric check (actual_hours >= 0),
  add column special_terms               text,
  add column facility_id                 integer references facility,                   -- "performed at"; none = the parent's site, or it doesn't matter
  add column work_effort_purpose_type_id text    references work_effort_purpose_type,   -- "for the purpose of"
  add check (actual_completion_datetime is null or actual_start_datetime is null
             or actual_completion_datetime >= actual_start_datetime);

create table production_run (
  work_effort_id      integer primary key references work_effort,
  quantity_to_produce numeric check (quantity_to_produce > 0),
  quantity_produced   numeric check (quantity_produced >= 0),
  quantity_rejected   numeric check (quantity_rejected >= 0)
);

-- WORK REQUIREMENT FULFILLMENT: which efforts fill which needs, many to many,
-- with nothing on the link. It references work_requirement, so the FK alone
-- keeps product needs out.
create table work_requirement_fulfillment (
  work_requirement_fulfillment_id integer generated by default as identity primary key,
  work_effort_id                  integer not null references work_effort,        -- "fulfilled by"
  requirement_id                  integer not null references work_requirement    -- "of"
);

-- ORDER ITEM's new subtype set, WORK or PRODUCT, has no attributes: a
-- discriminator defaulting to PRODUCT, so Ch 4's lines are unchanged (point
-- 12). WORK ORDER ITEM FULFILLMENT ties work straight to an order line; the
-- line must be a WORK item (a check).
alter table order_item
  add column order_item_kind text not null default 'PRODUCT' check (order_item_kind in ('PRODUCT', 'WORK'));

create table work_order_item_fulfillment (
  work_order_item_fulfillment_id integer generated by default as identity primary key,
  work_effort_id                 integer not null references work_effort,   -- "fulfilled by"
  order_item_id                  integer not null references order_item     -- "the fulfillment of" (a WORK item)
);

-- ============================================================
-- Fig 6.4 — Work effort breakdown
-- ============================================================
-- WORK EFFORT TYPE is a catalogue of kinds of work, each with a standard
-- (Table 6.6), and the five levels group them (NOTES, point 16): Ch 2's
-- table gains a parent, so a leaf's level is its parent row.
alter table work_effort_type
  add column parent_type_id text references work_effort_type;

-- WORK EFFORT ASSOCIATION and its subtypes, none with attributes: one table,
-- the subtype a row of a type hierarchy (DEPENDENCY groups PRECEDENCY and
-- CONCURRENCY). from → to: parent → part for a breakdown, first → second for
-- a precedency (point 19). Effective dates as from_date/thru_date.
create table work_effort_association_type (
  work_effort_association_type_id text primary key,
  parent_type_id                  text references work_effort_association_type,
  description                     text not null
);

create table work_effort_association (
  work_effort_association_id      integer generated by default as identity primary key,
  work_effort_association_type_id text    not null references work_effort_association_type,
  from_work_effort_id             integer not null references work_effort,   -- "associated with", from
  to_work_effort_id               integer not null references work_effort,   -- "associated with", to
  from_date                       date    not null,
  thru_date                       date,
  check (thru_date is null or thru_date > from_date),
  check (from_work_effort_id <> to_work_effort_id)
);

-- "a version of": a redo points at the effort it redoes.
alter table work_effort
  add column version_of_work_effort_id integer references work_effort,
  add check (version_of_work_effort_id <> work_effort_id);

-- ============================================================
-- Fig 6.5 — Work effort party assignment
-- ============================================================
-- Who works on an effort, as what, where and when. The book's key (effort,
-- party, role type, from date) lets the same party come back in the same
-- role; overlapping periods are a data-quality query. Facility optional.
create table work_effort_role_type (
  work_effort_role_type_id text primary key,
  description              text not null
);

create table work_effort_party_assignment (
  work_effort_party_assignment_id integer generated by default as identity primary key,
  work_effort_id                  integer not null references work_effort,             -- "for"
  party_id                        integer not null references party,                   -- "the assignment of"
  work_effort_role_type_id        text    not null references work_effort_role_type,   -- "described by"
  facility_id                     integer references facility,                         -- "assigned at"
  from_date                       date    not null,
  thru_date                       date,
  comment                         text,
  check (thru_date is null or thru_date > from_date)
);

-- What a party can do: a fact about the party, not about any assignment.
-- One row per party and skill (the book's key) is a data-quality query.
create table skill_type (
  skill_type_id text primary key,
  description   text not null
);

create table party_skill (
  party_skill_id   integer generated by default as identity primary key,
  party_id         integer not null references party,        -- "details about"
  skill_type_id    text    not null references skill_type,   -- "defined by"
  years_experience numeric check (years_experience >= 0),
  rating           numeric check (rating >= 0)
);

-- WORK EFFORT STATUS: a history of status events, as Ch 4's order status.
-- The types are rows of Ch 2's status_type under a WORK_EFFORT_STATUS group
-- (a check). The datetime is drawn optional (NOTES, point 22).
create table work_effort_status (
  work_effort_status_id integer generated by default as identity primary key,
  work_effort_id        integer not null references work_effort,   -- "for"
  status_type_id        text    not null references status_type,   -- "defined using"
  status_datetime       timestamptz
);

-- ============================================================
-- Fig 6.6 — Work effort time tracking
-- ============================================================
-- A timesheet gathers one worker's time for a period; it belongs to the
-- party's WORKER role (EMPLOYEE or CONTRACTOR, re-parented under WORKER in
-- Ch 2's role_type), which a plain FK can't check (a query). Each time entry
-- is hours on one effort. Nothing ties an entry to an assignment (point 24).
-- Timesheet thru_date is exclusive, like every thru date here.
create table timesheet (
  timesheet_id  integer generated by default as identity primary key,
  party_role_id integer not null references party_role,   -- "for the hours of" a WORKER
  from_date     date    not null,
  thru_date     date    not null,
  comment       text,
  check (thru_date > from_date)
);

create table time_entry (
  time_entry_id  integer generated by default as identity primary key,
  timesheet_id   integer     not null references timesheet,     -- "within"
  work_effort_id integer     not null references work_effort,   -- "the time spent on"
  from_datetime  timestamptz not null,
  thru_datetime  timestamptz not null,
  hours          numeric     not null check (hours >= 0),
  comment        text,
  check (thru_datetime > from_datetime)
);

-- Other parties on a timesheet: who approved it, who keyed it in.
create table timesheet_role_type (
  timesheet_role_type_id text primary key,
  description            text not null
);

create table timesheet_role (
  timesheet_role_id      integer generated by default as identity primary key,
  timesheet_id           integer not null references timesheet,             -- "for"
  party_id               integer not null references party,                 -- "of"
  timesheet_role_type_id text    not null references timesheet_role_type    -- "described by"
);

-- ============================================================
-- Fig 6.7 — Work effort rates
-- ============================================================
-- Rates at three levels, general to specific: a kind of position, a party,
-- one assignment. Each dated and typed (regular or overtime, billing or
-- pay). Which level wins is a business rule, not a line (NOTES, point 29):
-- a query picks the most specific. The rate is drawn optional; built not
-- null, since the row exists to carry it.
create table rate_type (
  rate_type_id text primary key,
  description  text not null
);

-- POSITION TYPE, ahead of Ch 9, which will extend it (point 30).
create table position_type (
  position_type_id text primary key,
  description      text not null
);

create table position_type_rate (
  position_type_rate_id integer generated by default as identity primary key,
  position_type_id      text    not null references position_type,   -- "for"
  rate_type_id          text    not null references rate_type,       -- "of"
  from_date             date    not null,
  thru_date             date,
  rate                  numeric(12, 2) not null check (rate >= 0),
  check (thru_date is null or thru_date > from_date)
);

create table party_rate (
  party_rate_id integer generated by default as identity primary key,
  party_id      integer not null references party,       -- "for"
  rate_type_id  text    not null references rate_type,   -- "of"
  from_date     date    not null,
  thru_date     date,
  rate          numeric(12, 2) not null check (rate >= 0),
  check (thru_date is null or thru_date > from_date)
);

-- That a rate lies within its assignment's dates is a data-quality query.
create table work_effort_assignment_rate (
  work_effort_assignment_rate_id  integer generated by default as identity primary key,
  work_effort_party_assignment_id integer not null references work_effort_party_assignment,   -- "with a rate of"
  rate_type_id                    text    not null references rate_type,                      -- "associated with"
  from_date                       date    not null,
  thru_date                       date,
  rate                            numeric(12, 2) not null check (rate >= 0),
  check (thru_date is null or thru_date > from_date)
);

-- ============================================================
-- Fig 6.8 — Inventory assignments
-- ============================================================
-- Stock a job uses up: which inventory item (Ch 3's), how much. The book
-- keys it on item and effort, so one row per item per effort (a check); a
-- serialized item is used whole, a quantity other than 1 is a check too.
-- Lowering quantity on hand is a business process, not a line (the text).
create table work_effort_inventory_assignment (
  work_effort_inventory_assignment_id integer generated by default as identity primary key,
  work_effort_id                      integer not null references work_effort,      -- "used in the completion of"
  inventory_item_id                   integer not null references inventory_item,   -- "the use of"
  quantity                            numeric check (quantity > 0)
);

-- ============================================================
-- Fig 6.9 — Fixed asset assignments
-- ============================================================
-- FIXED ASSET TYPE nests ("a type of"); its top rows are the drawn
-- subtypes PROPERTY, VEHICLE, EQUIPMENT and OTHER FIXED ASSET, none with
-- attributes. Capacity gets its unit.
alter table fixed_asset_type
  add column parent_type_id text references fixed_asset_type;   -- "a type of"

alter table fixed_asset
  add column description     text,
  add column capacity_uom_id text references unit_of_measure;   -- "associated with", the capacity uom

-- WORK EFFORT FIXED ASSET ASSIGNMENT: an asset booked on a job, dated, with
-- a current status (requested, assigned: Ch 2 status types under a group,
-- NOTES point 41) and the cost the job carries. From date is starred, not
-- in the key (point 31); one asset on two jobs at once is the check.
create table work_effort_fixed_asset_assignment (
  work_effort_fixed_asset_assignment_id integer generated by default as identity primary key,
  work_effort_id                        integer not null references work_effort,   -- "used to perform"
  fixed_asset_id                        integer not null references fixed_asset,   -- "a usage of"
  status_type_id                        text    not null references status_type,   -- "in the state of"
  from_date                             date    not null,
  thru_date                             date,
  allocated_cost                        numeric(12, 2) check (allocated_cost >= 0),
  comment                               text,
  check (thru_date is null or thru_date > from_date)
);

-- ============================================================
-- Fig 6.10 — Party fixed asset assignments
-- ============================================================
-- An asset checked out to a party, who answers for it while it's out: 6.9's
-- shape on the other end. Status (active, lost) from a second Ch 2 status
-- group. One holder at a time is a check, as is using an asset once lost.
create table party_fixed_asset_assignment (
  party_fixed_asset_assignment_id integer generated by default as identity primary key,
  party_id                        integer not null references party,         -- "an assignment to"
  fixed_asset_id                  integer not null references fixed_asset,   -- "an assignment for"
  status_type_id                  text    not null references status_type,   -- "in the state of"
  from_date                       date    not null,
  thru_date                       date,
  allocated_cost                  numeric(12, 2) check (allocated_cost >= 0),
  comment                         text,
  check (thru_date is null or thru_date > from_date)
);
