-- ============================================================
-- Fig 2.11 — Facility versus contact mechanism
-- ============================================================
-- A facility is a physical place (square footage, made of floors and rooms);
-- a contact mechanism is a way to reach someone. Facilities are reached
-- through their own link to contact mechanisms, just like parties.
--
-- The facility subtypes (WAREHOUSE, PLANT, BUILDING, FLOOR, OFFICE, ROOM)
-- have no attributes, so they are rows in the book's FACILITY TYPE table.

create table facility_type (
  facility_type_id text primary key,
  description      text not null
);

create table facility (
  facility_id         integer generated by default as identity primary key,
  facility_type_id    text    not null references facility_type,   -- "described by"
  part_of_facility_id integer references facility,                 -- "part of" (room → floor → building)
  description         text    not null,
  square_footage      numeric,
  check (part_of_facility_id <> facility_id)
);

create table facility_role_type (
  facility_role_type_id text primary key,
