create table facility_contact_mechanism (
  facility_contact_mechanism_id integer generated by default as identity primary key,
  facility_id                   integer not null references facility,            -- "contacted via"
  contact_mechanism_id          integer not null references contact_mechanism,   -- "used by"
  from_date                     date    not null,
  thru_date                     date,
  check (thru_date is null or thru_date > from_date)
