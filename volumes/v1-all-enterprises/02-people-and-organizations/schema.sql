-- Physical characteristics ------------------------------------

create table physical_characteristic_type (
  physical_characteristic_type_id text primary key,
  description                     text not null   -- the unit lives here, e.g. 'Height (cm)'
);

create table physical_characteristic (
  physical_characteristic_id      integer generated by default as identity primary key,
  party_id                        integer not null references person,
  physical_characteristic_type_id text    not null references physical_characteristic_type,
  from_date                       date    not null,
  thru_date                       date,
  value                           text,           -- one column for every characteristic: can't be type-checked
  check (thru_date is null or thru_date > from_date)
);

-- Citizenship and passports -----------------------------------

-- The country is a GEOGRAPHIC BOUNDARY of type COUNTRY (Fig 2.8); this table
-- had its own `country` lookup until 2.8 folded it in.
create table citizenship (
  citizenship_id integer generated by default as identity primary key,
  party_id       integer not null references person,
  country_id     integer not null references geographic_boundary,   -- must be a COUNTRY (data-quality query)
  from_date      date    not null,
  thru_date      date,
  check (thru_date is null or thru_date > from_date)
);

-- A passport hangs off a citizenship: the person and country are reached
-- through it.
create table passport (
  passport_id     integer generated by default as identity primary key,
  citizenship_id  integer not null references citizenship,
  passport_num    text    not null,
  issue_date      date    not null,
  expiration_date date    not null,
  check (expiration_date > issue_date)
);

-- ============================================================
-- Fig 2.3 (part 2) — Party classification
-- ============================================================
-- Subtype = what a party IS (fixed, exactly one). Classification = how we
-- categorise it (many, dated, just data). The classification subtypes in the
-- book (organization: minority/industry/size; person: EEOC/income) have no
-- attributes, so they become a three-level party_type hierarchy:
--   ORGANIZATION_CLASSIFICATION > INDUSTRY > IND_LOGISTICS
--
-- applies_to_kind records which kind of party a type is for; a data-quality
-- query catches mismatches (e.g. an INDUSTRY classification on a person).

create table party_type (
  party_type_id   text primary key,
  parent_type_id  text references party_type,
  applies_to_kind text not null check (applies_to_kind in ('PERSON', 'ORGANIZATION')),
  description     text not null
);

create table party_classification (
  party_classification_id integer generated by default as identity primary key,
  party_id                integer not null references party,
  party_type_id           text    not null references party_type,
  from_date               date    not null,
  thru_date               date,
  check (thru_date is null or thru_date > from_date)
);

-- Current display name for any party (person or organization). Later chapters
-- will want "the name of party X" constantly; this is where the supertype pays off.
create view party_display_name as
select p.party_id,
       p.party_kind,
       coalesce(
         o.name,
         concat_ws(' ',
           max(n.name) filter (where n.person_name_type_id = 'FIRST'),
           max(n.name) filter (where n.person_name_type_id = 'LAST'))
       ) as name
from party p
left join organization o on o.party_id = p.party_id
left join person_name n  on n.party_id = p.party_id and n.thru_date is null
group by p.party_id, p.party_kind, o.name;

-- ============================================================
-- Fig 2.4 — Party roles
-- ============================================================
-- A role is something a party *plays* (customer, supplier, employee), not
-- something it *is*. One party can hold many roles, each dated.
--
-- ROLE TYPE is drawn as a supertype whose only subtype so far is PARTY ROLE
-- TYPE; one role_type table is enough until another subtype appears. The
-- book's role subtypes (PERSON ROLE > EMPLOYEE, ORGANIZATION ROLE >
-- DISTRIBUTION CHANNEL > AGENT, …) become a role_type hierarchy.
--
-- applies_to_kind: which kind of party may play the role. EITHER for
-- CUSTOMER/PROSPECT/SHAREHOLDER; null for grouping types (PERSON_ROLE,
-- DISTRIBUTION_CHANNEL…) that are not assigned directly. A data-quality query
-- catches roles played by the wrong kind of party.

create table role_type (
  role_type_id    text primary key,
  parent_type_id  text references role_type,
  applies_to_kind text check (applies_to_kind in ('PERSON', 'ORGANIZATION', 'EITHER')),
  description     text not null
);

create table party_role (
  party_role_id integer generated by default as identity primary key,
  party_id      integer not null references party,
  role_type_id  text    not null references role_type,
  from_date     date    not null,   -- * in the book: mandatory, but not part of the identifier
  thru_date     date,
  check (thru_date is null or thru_date > from_date)
);

-- ============================================================
-- Fig 2.5 — Specific party relationships
-- ============================================================
-- One table per kind of relationship, each linking two party roles. The book
-- draws them as subtypes of PARTY RELATIONSHIP; the supertype has only dates,
-- so each subtype table carries its own. Fig 2.6a replaces all of this with a
-- generic party_relationship; these tables stay loaded for comparison.
--
-- Plain FKs only: nothing here checks that employee_party_role_id is really an
-- EMPLOYEE role. queries.sql has a data-quality check for that.

create table employment (
  employment_id          integer generated by default as identity primary key,
  employer_party_role_id integer not null references party_role,   -- "from": INTERNAL ORGANIZATION
  employee_party_role_id integer not null references party_role,   -- "to":   EMPLOYEE
  from_date              date    not null,
  thru_date              date,
  check (thru_date is null or thru_date > from_date)
);

create table customer_relationship (
  customer_relationship_id        integer generated by default as identity primary key,
  customer_party_role_id          integer not null references party_role,   -- "from": CUSTOMER (any kind)
  internal_org_party_role_id      integer not null references party_role,   -- "to":   INTERNAL ORGANIZATION
  from_date                       date    not null,
  thru_date                       date,
  check (thru_date is null or thru_date > from_date)
);

create table organization_rollup (
  organization_rollup_id integer generated by default as identity primary key,
  child_party_role_id    integer not null references party_role,   -- "from": ORGANIZATION UNIT ("within")
  parent_party_role_id   integer not null references party_role,   -- "to":   ORGANIZATION ROLE ("made up of")
  from_date              date    not null,
  thru_date              date,
  check (thru_date is null or thru_date > from_date)
);

-- ============================================================
-- Fig 2.6a — Common party relationships (generic)
-- ============================================================
-- One table for every kind of relationship. What 2.5 expressed as separate
-- tables and self-explaining column names becomes data: a relationship TYPE
-- row that names the role type expected at each end. The 2.5 tables stay
-- loaded for comparison.
--
-- The book's relationship subtypes (EMPLOYMENT, CUSTOMER RELATIONSHIP, …)
-- have no attributes, so they are rows in party_relationship_type.

create table party_relationship_type (
  party_relationship_type_id text primary key,
  name                       text not null,
  description                text not null,
  from_role_type_id          text not null references role_type,   -- "used to define" (from)
  to_role_type_id            text not null references role_type    -- "used to define" (to)
);

create table party_relationship (
  party_relationship_id      integer generated by default as identity primary key,
  party_relationship_type_id text    not null references party_relationship_type,
  from_party_role_id         integer not null references party_role,
  to_party_role_id           integer not null references party_role,
  from_date                  date    not null,
  thru_date                  date,
  comment                    text,
  check (thru_date is null or thru_date > from_date)
);

-- Every role type paired with itself and each of its ancestors, e.g.
-- (BILL_TO_CUSTOMER, BILL_TO_CUSTOMER), (BILL_TO_CUSTOMER, CUSTOMER).
-- Lets a query ask "is this role a kind of CUSTOMER?" at any depth.
create view role_type_ancestor as
with recursive walk (role_type_id, ancestor_id) as (
  select role_type_id, role_type_id from role_type
  union all
  select w.role_type_id, t.parent_type_id
  from walk w
  join role_type t on t.role_type_id = w.ancestor_id
  where t.parent_type_id is not null
)
select role_type_id, ancestor_id from walk;

-- ============================================================
-- Fig 2.7 — Party relationship information
-- ============================================================
-- A relationship gets an optional priority and status (current values only,
-- no history) and a log of communication events within it.

create table priority_type (
  priority_type_id text primary key,
  description      text not null
);

-- STATUS TYPE is drawn as a supertype whose only subtype so far is PARTY
-- RELATIONSHIP STATUS TYPE. As with role_type, one table with a parent
-- column: relationship statuses sit under a PARTY_RELATIONSHIP_STATUS
-- grouping row, and later chapters can add their own groups. A data-quality
-- query checks a relationship only uses relationship statuses.
create table status_type (
  status_type_id text primary key,
  parent_type_id text references status_type,
  description    text not null
);

-- Added to the 2.6a table: both optional (dashed on the relationship side).
alter table party_relationship
  add column priority_type_id text references priority_type,
  add column status_type_id   text references status_type;

create table communication_event (
  communication_event_id integer generated by default as identity primary key,
  party_relationship_id  integer     not null references party_relationship,   -- "in the context of"
  datetime_started       timestamptz not null,
  datetime_ended         timestamptz,
  note                   text,
  check (datetime_ended is null or datetime_ended >= datetime_started)
);

-- ============================================================
-- Fig 2.8 (part 2) — Postal address information
-- ============================================================
-- The address is stored once and linked to parties with dates. Only the
-- street part lives on the address; city, state, postal code and country are
-- geographic boundaries it is linked to.

-- How boundaries nest. Many-to-many: a postal code can cross city lines, a
-- sales territory can span states. "from" is the smaller boundary (within),
-- "to" the one containing it (in). The specific lines drawn between subtypes
-- in the book (city within state, COUNTY CITY…) are all rows here.
create table geographic_boundary_association (
  geographic_boundary_association_id integer generated by default as identity primary key,
  from_geographic_boundary_id        integer not null references geographic_boundary,   -- within
  to_geographic_boundary_id          integer not null references geographic_boundary,   -- in
  check (from_geographic_boundary_id <> to_geographic_boundary_id)
);

create table postal_address (
  postal_address_id integer generated by default as identity primary key,   -- no identifier drawn in the book
  address1          text not null,
  address2          text,
  directions        text
);

create table party_postal_address (
  party_postal_address_id integer generated by default as identity primary key,
  party_id                integer not null references party,            -- "residing at"
  postal_address_id       integer not null references postal_address,   -- "located at"
  from_date               date    not null,
  thru_date               date,
  comment                 text,
  check (thru_date is null or thru_date > from_date)
);

create table postal_address_boundary (
  postal_address_boundary_id integer generated by default as identity primary key,
  postal_address_id          integer not null references postal_address,
  geographic_boundary_id     integer not null references geographic_boundary
);

-- Every boundary paired with itself and every boundary that contains it, at
-- any depth (62707 → Chatham → Illinois → United States → North America).
create view geographic_boundary_ancestor as
with recursive walk (geographic_boundary_id, ancestor_id, depth) as (
  select geographic_boundary_id, geographic_boundary_id, 0 from geographic_boundary
  union all
  select w.geographic_boundary_id, a.to_geographic_boundary_id, w.depth + 1
  from walk w
  join geographic_boundary_association a on a.from_geographic_boundary_id = w.ancestor_id
  where w.depth < 10   -- guard against cycles
)
select distinct geographic_boundary_id, ancestor_id from walk;

-- ============================================================
-- Fig 2.9 — Party contact mechanism: telecommunications numbers and electronic addresses
-- ============================================================
-- Same shape as 2.8: a contact mechanism is stored once and linked to parties
-- with dates. The two subtypes have their own attributes, so they are real
-- subtype tables sharing the supertype's PK, with contact_mechanism_kind as the
-- discriminator. CONTACT MECHANISM TYPE (phone, mobile, fax, e-mail…) is a
-- second, independent classification by use.

create table contact_mechanism_type (
  contact_mechanism_type_id text primary key,
  -- Addition: which subtype a type fits. Checked by a data-quality query.
  applies_to_kind           text not null check (applies_to_kind in ('TELECOMMUNICATIONS_NUMBER', 'ELECTRONIC_ADDRESS')),
  description               text not null
);

create table contact_mechanism (
  contact_mechanism_id      integer generated by default as identity primary key,
  contact_mechanism_kind    text not null check (contact_mechanism_kind in ('TELECOMMUNICATIONS_NUMBER', 'ELECTRONIC_ADDRESS')),
  contact_mechanism_type_id text not null references contact_mechanism_type   -- "described by"
);

create table telecommunications_number (
  contact_mechanism_id integer primary key references contact_mechanism,
  country_code         text,            -- optional: assumed domestic when null
  area_code            text not null,
  contact_number       text not null
);

create table electronic_address (
  contact_mechanism_id      integer primary key references contact_mechanism,
  electronic_address_string text not null
);

create table party_contact_mechanism (
  party_contact_mechanism_id integer generated by default as identity primary key,
  party_id                   integer not null references party,               -- "contacted via"
  contact_mechanism_id       integer not null references contact_mechanism,   -- "used by"
  from_date                  date    not null,
  thru_date                  date,
  non_solicitation_ind       boolean,   -- true = don't market to this party through this mechanism
  comment                    text,
  check (thru_date is null or thru_date > from_date)
);
