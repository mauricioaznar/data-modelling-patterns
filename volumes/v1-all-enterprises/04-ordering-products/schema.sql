-- Vol 1, Chapter 4: Ordering Products
-- Built up one figure at a time; each section is headed by the figure it implements.
-- Fig 4.1 (the standard order model) is not built: Fig 4.2 replaces it (NOTES).

-- ============================================================
-- Fig 4.2 — Orders and order items
-- ============================================================
-- One ORDER for both directions. SALES ORDER and PURCHASE ORDER have no
-- attributes of their own here, so they become an order_kind discriminator
-- (as product_kind in Ch 3). SALES ORDER gets a subtype table in 4.3, when
-- it gets relationships of its own.
--
-- ORDER is a reserved word, so the table is "order", quoted. Only the table
-- name needs the quotes: order_id, order_date and order_item are plain.

create table "order" (
  order_id   integer generated by default as identity primary key,
  order_kind text not null check (order_kind in ('SALES', 'PURCHASE')),
  order_date date not null,   -- when the order was placed
  entry_date date             -- when we keyed it in
);

-- An item is identified by its order plus a line number (the bar on "part
-- of"). We keep a surrogate key; the line number's uniqueness within the
-- order is a data-quality query.
--
-- An item is for a product, or for one of its features ("ordered for" the
-- product's item), or for neither when its description says what it is (a
-- one-off). The book draws no arc; our reading (NOTES, point 2) is checked by
-- data-quality queries.
--
-- unit_price is what was agreed on the order date, frozen: Ch 3's price
-- components are only the rules that suggested it. USD; the quantity is in
-- the product's unit of measure.
create table order_item (
  order_item_id             integer generated by default as identity primary key,
  order_id                  integer not null references "order",   -- "part of"
  order_item_seq_id         integer not null,                      -- the line number within the order
  product_id                integer references product,            -- "for"
  product_feature_id        integer references product_feature,    -- "for"
  ordered_for_order_item_id integer references order_item,         -- "ordered for" another item
  quantity                  numeric check (quantity > 0),
  unit_price                numeric check (unit_price >= 0),
  estimated_delivery_date   date,
  shipping_instructions     text,
  item_description          text,
  comment                   text,
  check (ordered_for_order_item_id <> order_item_id)
);

-- SALES ORDER ITEM has an attribute, so it's a subtype table sharing the PK.
-- PURCHASE ORDER ITEM has none and gets no table until 4.4. No discriminator on
-- order_item: an item's kind is its order's kind (a data-quality query checks
-- that sales items, and only they, have a row here).
create table sales_order_item (
  order_item_id       integer primary key references order_item,
  corresponding_po_id text   -- the customer's own purchase order number for this line
);

-- ============================================================
-- Fig 4.3 — Sales order parties and contact mechanisms
-- ============================================================
-- SALES ORDER now has relationships of its own, so it gets a subtype table
-- sharing order_id (as GOOD did in Ch 3, Fig 3.3). order_kind stays the
-- discriminator; a data-quality query checks the two agree.
--
-- The party lines point at PARTY ROLE (Ch 2, Fig 2.4), not at PARTY: the
-- order names "Contoso as bill-to customer", a dated role row. The role's
-- type (PLACING_CUSTOMER, INTERNAL_ORGANIZATION, BILL_TO_CUSTOMER or one below
-- it) and its dates are data-quality queries.
--
-- The contact mechanism lines point at CONTACT MECHANISM, of any kind: an
-- order comes in by phone, e-mail or the website, and a bill can go by e-mail.
-- Every line is optional (NOTES, point 3); with no bill-to, the queries bill
-- the placing customer.

create table sales_order (
  order_id                          integer primary key references "order",
  placed_by_party_role_id           integer references party_role,          -- PLACING CUSTOMER: "placed by"
  taken_by_party_role_id            integer references party_role,          -- INTERNAL ORGANIZATION: "taken by"
  bill_to_party_role_id             integer references party_role,          -- BILL TO CUSTOMER: "with a requested bill to"
  placed_using_contact_mechanism_id integer references contact_mechanism,   -- "placed using"
  taken_via_contact_mechanism_id    integer references contact_mechanism,   -- "taken via"
  bill_to_contact_mechanism_id      integer references contact_mechanism    -- "designated to be billed to"
);

-- Ship-to sits on the item: one bill, many destinations. A feature item
-- ships with the item it's ordered for (the queries fall back to it).
alter table sales_order_item
  add column ship_to_party_role_id        integer references party_role,          -- SHIP TO CUSTOMER: "designated to be shipped to"
  add column ship_to_contact_mechanism_id integer references contact_mechanism;   -- "designated to be shipped to"

-- ORDER ROLE: any other party on an order (a salesperson, whoever keyed it
-- in, an approver). It hangs on ORDER, so purchase orders have them too. It
-- names a PARTY and a type, not a PARTY ROLE: being this order's salesperson
-- is a role within the order only.
--
-- ORDER ROLE TYPE is a lookup of its own for now. Ch 2's role_type could
-- become a ROLE TYPE supertype with party and order role subtypes (TODO,
-- Fig 2.4); that waits for the overview (NOTES, point 5).
--
-- The identifier is order + party + type (point 4), and the shares of one
-- type on one order add up to at most 100: both data-quality queries.
create table order_role_type (
  order_role_type_id text primary key,
  description        text not null
);

create table order_role (
  order_role_id        integer generated by default as identity primary key,
  order_id             integer not null references "order",           -- "of"
  party_id             integer not null references party,             -- "involving"
  order_role_type_id   text    not null references order_role_type,   -- "described by"
  percent_contribution numeric check (percent_contribution between 0 and 100)   -- e.g. a salesperson's share of the sale
);

-- A helper, no book entity: one line of text per contact mechanism, so
-- queries can show where an order goes. Named like party_display_name, which
-- also lets the explorer label contact mechanism ids.
create view contact_mechanism_display_name as
select cm.contact_mechanism_id,
       coalesce(
         pa.address1 || coalesce(', ' || pa.address2, ''),
         case when t.contact_mechanism_id is not null   -- concat_ws gives '' for no number, not null
              then concat_ws(' ', '+' || t.country_code, t.area_code, t.contact_number) end,
         e.electronic_address_string
       ) as display_name
from contact_mechanism cm
left join postal_address pa           on pa.contact_mechanism_id = cm.contact_mechanism_id
left join telecommunications_number t on t.contact_mechanism_id = cm.contact_mechanism_id
left join electronic_address e        on e.contact_mechanism_id = cm.contact_mechanism_id;

-- ============================================================
-- Fig 4.4 — Purchase order parties and contact mechanisms
-- ============================================================
-- Fig 4.3 turned over: PURCHASE ORDER gets a subtype table with the same six
-- lines, and PURCHASE ORDER ITEM one with the ship-to pair. The same column
-- names as sales_order, so the mirror shows. The roles expected are the
-- buyer's side (PLACING_BUYER, SUPPLIER, BILL_TO_PURCHASER, SHIP_TO_BUYER),
-- checked by data-quality queries copied from 4.3's: the cost of the twins.
--
-- PURCHASE ORDER ITEM is drawn with its own ITEM DESCRIPTION; read as
-- order_item's (NOTES, point 6), so this table holds only the ship-to pair.

create table purchase_order (
  order_id                          integer primary key references "order",
  placed_by_party_role_id           integer references party_role,          -- PLACING BUYER: "placed by"
  taken_by_party_role_id            integer references party_role,          -- SUPPLIER: "taken by"
  bill_to_party_role_id             integer references party_role,          -- BILL TO PURCHASER: "with a requested bill to"
  placed_using_contact_mechanism_id integer references contact_mechanism,   -- "placed using"
  taken_via_contact_mechanism_id    integer references contact_mechanism,   -- "taken via"
  bill_to_contact_mechanism_id      integer references contact_mechanism    -- "designated to be billed to"
);

create table purchase_order_item (
  order_item_id                integer primary key references order_item,
  ship_to_party_role_id        integer references party_role,          -- SHIP TO BUYER: "designated to be shipped to"
  ship_to_contact_mechanism_id integer references contact_mechanism    -- "designated to be shipped to"
);

-- ============================================================
-- Fig 4.5 — Generic order roles and contact mechanisms
-- ============================================================
-- The book's flexible alternate to 4.3 and 4.4: every party and contact
-- mechanism on an order or an item is a row with a type, in both directions.
-- ORDER ROLE and ORDER ROLE TYPE are 4.3's tables; the rest is new. Both
-- versions stay loaded, as Ch 2 kept Figs 2.5 and 2.6a (NOTES, point 8).
--
-- What the columns gave for free becomes data-quality queries: one placer,
-- taker and bill-to per order, the identifiers (a bar on all three lines of
-- each table), and no order naming the same job both ways.

create table order_item_role_type (
  order_item_role_type_id text primary key,
  description             text not null
);

create table order_item_role (
  order_item_role_id      integer generated by default as identity primary key,
  order_item_id           integer not null references order_item,             -- "of"
  party_id                integer not null references party,                  -- "assigned to"
  order_item_role_type_id text    not null references order_item_role_type    -- "described by"
);

-- CONTACT MECHANISM PURPOSE TYPE is Ch 2's (Fig 2.10): one list of purposes
-- for a party's mechanisms and an order's.
create table order_contact_mechanism (
  order_contact_mechanism_id        integer generated by default as identity primary key,
  order_id                          integer not null references "order",                         -- "used with"
  contact_mechanism_id              integer not null references contact_mechanism,               -- "assigned to"
  contact_mechanism_purpose_type_id text    not null references contact_mechanism_purpose_type   -- "used for"
);

create table order_item_contact_mechanism (
  order_item_contact_mechanism_id   integer generated by default as identity primary key,
  order_item_id                     integer not null references order_item,                      -- "used with"
  contact_mechanism_id              integer not null references contact_mechanism,               -- "assigned to"
  contact_mechanism_purpose_type_id text    not null references contact_mechanism_purpose_type   -- "used for"
);

-- ============================================================
-- Fig 4.6 — Order adjustments
-- ============================================================
-- Everything that changes an order's price besides quantity × unit price:
-- discounts, surcharges, sales tax, shipping and handling, fees. One row per
-- adjustment, typed, for the whole order or for one item.
--
-- The six subtypes have no attributes, so they become the top level of
-- ORDER ADJUSTMENT TYPE, with finer types under them (Ch 3's cost component
-- move). A data-quality query checks every type rolls up to one of the six.

create table order_adjustment_type (
  order_adjustment_type_id text primary key,
  parent_type_id           text references order_adjustment_type,
  description              text not null
);

-- For the whole order or for one item: no arc is drawn, so "exactly one" is
-- a data-quality query (NOTES, point 10), as is "an amount or a percentage".
-- Both are stored positive: a DISCOUNT lowers the price, every other type
-- raises it. A percentage is of the order's or the item's value before any
-- adjustment (point 11).
create table order_adjustment (
  order_adjustment_id      integer generated by default as identity primary key,
  order_adjustment_type_id text    not null references order_adjustment_type,   -- "described by"
  order_id                 integer references "order",                          -- "affecting" the whole order
  order_item_id            integer references order_item,                       -- "affecting" one item
  amount                   numeric check (amount >= 0),
  percentage               numeric check (percentage > 0 and percentage <= 100)
);

-- The rate a geographic boundary charges, on every product or on one
-- category. A SALES TAX adjustment copies its percentage from here on the
-- order date; no line joins them, so a rate change leaves old orders alone.
-- No dates drawn (point 12). Our key stands in for the book's sales_tax_seq_id.
create table sales_tax_lookup (
  sales_tax_lookup_id    integer generated by default as identity primary key,
  geographic_boundary_id integer not null references geographic_boundary,   -- "for"
  product_category_id    integer references product_category,               -- "specified for"; null = every category
  sales_tax_percentage   numeric not null check (sales_tax_percentage >= 0)
);

-- ============================================================
-- Fig 4.7 — Order status and terms
-- ============================================================
-- ORDER STATUS: a dated history of where an order, or one of its items,
-- stands; the current status is the latest row. ORDER STATUS TYPE becomes an
-- ORDER_STATUS group in Ch 2's shared status_type, beside the relationship,
-- event and case statuses (NOTES, point 15). A data-quality query checks the
-- group.
--
-- A status or a term is for the whole order or for one item. No arc is
-- drawn, so "exactly one" is a data-quality query, as for 4.6's adjustments
-- (point 14).
create table order_status (
  order_status_id integer generated by default as identity primary key,
  status_type_id  text        not null references status_type,   -- "described by"
  order_id        integer     references "order",                -- "a status for" the whole order
  order_item_id   integer     references order_item,             -- "a status for" one item
  status_datetime timestamptz not null
);

-- TERM TYPE has no ORDER in its name: read as a list other kinds of terms
-- will share (point 15). Flat, as drawn.
create table term_type (
  term_type_id text primary key,
  description  text not null
);

-- ORDER TERM: a condition agreed for an order or one of its items. The value
-- is a bare number whose meaning (a percentage, a number of days) comes from
-- its type; some terms need none (point 13).
create table order_term (
  order_term_id integer generated by default as identity primary key,
  term_type_id  text    not null references term_type,   -- "described by"
  order_id      integer references "order",              -- "a condition for" the whole order
  order_item_id integer references order_item,           -- "a condition for" one item
  term_value    numeric
);

-- ============================================================
-- Fig 4.8 — Order item association
-- ============================================================
-- Which purchase line will fill which sales line: a sale we can't fill from
-- stock gets bought, and the sales line waits on the purchase. Many to many.
-- The lines land on the subtypes, so the FKs point at the subtype tables and
-- a plain FK keeps the direction (a sale is filled by a purchase). No
-- quantity is drawn (NOTES, point 17). The identifier (both items) is a
-- data-quality query.
create table order_item_association (
  order_item_association_id integer generated by default as identity primary key,
  sales_order_item_id       integer not null references sales_order_item,      -- "from"
  purchase_order_item_id    integer not null references purchase_order_item    -- "to": "used to fulfill"
);
