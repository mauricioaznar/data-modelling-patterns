-- Vol 1, Chapter 5: Shipments
-- Built up one figure at a time; each section is headed by the figure it implements.

-- ============================================================
-- Fig 5.1 — Shipment definition
-- ============================================================
-- A SHIPMENT moves goods from one party and address to another. It's planned
-- before it happens: the estimates sit on it, and what actually happened goes
-- into Fig 5.2's status history.
--
-- The subtypes have no attributes, so they become rows in a shipment_type
-- hierarchy (NOTES, point 2): OUTGOING and INCOMING are grouping rows over
-- their two subtypes each; TRANSFER and DROP SHIPMENT stand alone. A
-- shipment uses a leaf type, a data-quality query.
--
-- from_internal and to_internal are ours, not the book's: whether each end
-- of a shipment of this type is one of our own organizations. A type is a
-- direction, so the rule is stored as data and checked against the parties'
-- INTERNAL_ORGANIZATION roles (Ch 2) by a data-quality query.
create table shipment_type (
  shipment_type_id text primary key,
  parent_type_id   text references shipment_type,
  from_internal    boolean,   -- null on the grouping rows
  to_internal      boolean,
  description      text not null
);

-- The party lines are mandatory, the rest optional (point 1). The address
-- lines land on POSTAL ADDRESS and the receiving number's on
-- TELECOMMUNICATIONS NUMBER, so those FKs point at the subtype tables and a
-- plain FK keeps the kind. That an address is one its party has on file is
-- a data-quality query.
create table shipment (
  shipment_id                       integer generated by default as identity primary key,
  shipment_type_id                  text    not null references shipment_type,
  estimated_ship_date               date    not null,
  estimated_ready_date              date,
  estimated_arrival_date            date,
  estimated_ship_cost               numeric check (estimated_ship_cost >= 0),   -- USD
  actual_ship_cost                  numeric check (actual_ship_cost >= 0),
  latest_cancel_date                date,          -- the last day it can still be called off
  handling_instructions             text,
  last_updated                      timestamptz,
  shipped_from_party_id             integer not null references party,                -- "shipped from": the sender
  shipped_to_party_id               integer not null references party,                -- "shipped to": the receiver
  shipped_from_contact_mechanism_id integer references postal_address,                 -- "shipped from": the source
  shipped_to_contact_mechanism_id   integer references postal_address,                 -- "shipped to": the destination
  inquiry_contact_mechanism_id      integer references contact_mechanism,              -- "inquired about via"
  receiving_contact_mechanism_id    integer references telecommunications_number       -- "facilitated via": the receiving contact number
);

-- A helper, no book entity: whether each end of a shipment is one of our own
-- organizations (a current INTERNAL_ORGANIZATION role, Ch 2) on its
-- estimated ship date. Queries set it beside the type's two flags.
create view shipment_end as
select s.shipment_id,
       exists (select 1 from party_role r
               where r.party_id = s.shipped_from_party_id
                 and r.role_type_id = 'INTERNAL_ORGANIZATION'
                 and r.from_date <= s.estimated_ship_date
                 and (r.thru_date is null or r.thru_date > s.estimated_ship_date)) as from_internal,
       exists (select 1 from party_role r
               where r.party_id = s.shipped_to_party_id
                 and r.role_type_id = 'INTERNAL_ORGANIZATION'
                 and r.from_date <= s.estimated_ship_date
                 and (r.thru_date is null or r.thru_date > s.estimated_ship_date)) as to_internal
from shipment s;

-- ============================================================
-- Fig 5.2 — Shipping detail
-- ============================================================
-- SHIPMENT ITEM: what's on the truck. An item is identified by its shipment
-- plus a line number (the bar on "part of"); we keep a surrogate key and the
-- line number's uniqueness is a data-quality query.
--
-- The line lands on GOOD, so the FK points at Ch 3's good table: services
-- don't ship. Optional (NOTES, point 5): a line can describe contents that
-- aren't a catalogue good instead. "In response to" ties a return (or a
-- replacement) to the line it answers.
create table shipment_item (
  shipment_item_id                integer generated by default as identity primary key,
  shipment_id                     integer not null references shipment,   -- "part of"
  shipment_item_seq_id            integer not null,                       -- the line number within the shipment
  product_id                      integer references good,                -- "a shipment of"
  quantity                        numeric not null check (quantity > 0),  -- in the good's unit of measure
  shipment_contents_description   text,
  in_response_to_shipment_item_id integer references shipment_item,       -- "in response to"
  check (in_response_to_shipment_item_id <> shipment_item_id)
);

-- SHIPMENT STATUS: what actually happened, and when. The book draws no id:
-- shipment + status type identify it (two bars), so a shipment has one
-- status of each type (point 6). Surrogate key; the identifier is a
-- data-quality query. SHIPMENT STATUS TYPE becomes a SHIPMENT_STATUS group
-- in Ch 2's shared status_type, beside Ch 4's order statuses (point 7).
create table shipment_status (
  shipment_status_id integer generated by default as identity primary key,
  shipment_id        integer     not null references shipment,      -- "the history for"
  status_type_id     text        not null references status_type,   -- "defined using"
  status_datetime    timestamptz not null                           -- STATUS DATE: times allowed, as the text says
);

-- ============================================================
-- Fig 5.3 — Shipment-to-order relationship
-- ============================================================
-- ORDER SHIPMENT: how much of an order line (Ch 4) went out on a shipment
-- line. Many to many, with a quantity, so an order line can ship in parts
-- and a shipment line can fill lines of several orders. The book draws no
-- id: the two barred lines identify it (NOTES, point 11). Surrogate key; the
-- pair twice is a data-quality query, and so are the rules the text leaves
-- to business processes (the same good, the same destination, no more than
-- the shipment line carries) and the direction (point 15).
create table order_shipment (
  order_shipment_id integer generated by default as identity primary key,
  order_item_id     integer not null references order_item,       -- "the shipment of"
  shipment_item_id  integer not null references shipment_item,    -- "shipped via"
  quantity          numeric not null check (quantity > 0)
);

-- SHIPMENT ITEM FEATURE: the features a shipment line actually went out with,
-- to set beside what its order lines asked for (point 16). No attributes;
-- the pair twice is the data-quality query above.
create table shipment_item_feature (
  shipment_item_feature_id integer generated by default as identity primary key,
  shipment_item_id         integer not null references shipment_item,     -- "for"
  product_feature_id       integer not null references product_feature    -- "of"
);
