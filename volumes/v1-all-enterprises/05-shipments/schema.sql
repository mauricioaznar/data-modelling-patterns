-- Vol 1, Chapter 5: Shipments
-- Built up one figure at a time; each section is headed by the figure it implements.

-- ============================================================
-- Fig 5.1 — Shipment definition
-- ============================================================
-- A SHIPMENT moves goods from one party and address to another. It's planned
-- before it happens: the estimates sit on it, and what actually happened goes
-- into Fig 5.2's status history.
--
-- The subtypes have no attributes, so they become rows in a shipment_type
-- hierarchy (NOTES, point 2): OUTGOING and INCOMING are grouping rows over
-- their two subtypes each; TRANSFER and DROP SHIPMENT stand alone. A
-- shipment uses a leaf type, a data-quality query.
--
-- from_internal and to_internal are ours, not the book's: whether each end
-- of a shipment of this type is one of our own organizations. A type is a
-- direction, so the rule is stored as data and checked against the parties'
-- INTERNAL_ORGANIZATION roles (Ch 2) by a data-quality query.
create table shipment_type (
  shipment_type_id text primary key,
  parent_type_id   text references shipment_type,
  from_internal    boolean,   -- null on the grouping rows
  to_internal      boolean,
  description      text not null
);

-- The party lines are mandatory, the rest optional (point 1). The address
-- lines land on POSTAL ADDRESS and the receiving number's on
-- TELECOMMUNICATIONS NUMBER, so those FKs point at the subtype tables and a
-- plain FK keeps the kind. That an address is one its party has on file is
-- a data-quality query.
create table shipment (
  shipment_id                       integer generated by default as identity primary key,
  shipment_type_id                  text    not null references shipment_type,
  estimated_ship_date               date    not null,
  estimated_ready_date              date,
  estimated_arrival_date            date,
  estimated_ship_cost               numeric check (estimated_ship_cost >= 0),   -- USD
  actual_ship_cost                  numeric check (actual_ship_cost >= 0),
  latest_cancel_date                date,          -- the last day it can still be called off
  handling_instructions             text,
  last_updated                      timestamptz,
  shipped_from_party_id             integer not null references party,                -- "shipped from": the sender
  shipped_to_party_id               integer not null references party,                -- "shipped to": the receiver
  shipped_from_contact_mechanism_id integer references postal_address,                 -- "shipped from": the source
  shipped_to_contact_mechanism_id   integer references postal_address,                 -- "shipped to": the destination
  inquiry_contact_mechanism_id      integer references contact_mechanism,              -- "inquired about via"
  receiving_contact_mechanism_id    integer references telecommunications_number       -- "facilitated via": the receiving contact number
);

-- A helper, no book entity: whether each end of a shipment is one of our own
-- organizations (a current INTERNAL_ORGANIZATION role, Ch 2) on its
-- estimated ship date. Queries set it beside the type's two flags.
create view shipment_end as
select s.shipment_id,
       exists (select 1 from party_role r
               where r.party_id = s.shipped_from_party_id
                 and r.role_type_id = 'INTERNAL_ORGANIZATION'
                 and r.from_date <= s.estimated_ship_date
                 and (r.thru_date is null or r.thru_date > s.estimated_ship_date)) as from_internal,
       exists (select 1 from party_role r
               where r.party_id = s.shipped_to_party_id
                 and r.role_type_id = 'INTERNAL_ORGANIZATION'
                 and r.from_date <= s.estimated_ship_date
                 and (r.thru_date is null or r.thru_date > s.estimated_ship_date)) as to_internal
from shipment s;

-- ============================================================
-- Fig 5.2 — Shipping detail
-- ============================================================
-- SHIPMENT ITEM: what's on the truck. An item is identified by its shipment
-- plus a line number (the bar on "part of"); we keep a surrogate key and the
-- line number's uniqueness is a data-quality query.
--
-- The line lands on GOOD, so the FK points at Ch 3's good table: services
-- don't ship. Optional (NOTES, point 5): a line can describe contents that
-- aren't a catalogue good instead. "In response to" ties a return (or a
-- replacement) to the line it answers.
create table shipment_item (
  shipment_item_id                integer generated by default as identity primary key,
  shipment_id                     integer not null references shipment,   -- "part of"
  shipment_item_seq_id            integer not null,                       -- the line number within the shipment
  product_id                      integer references good,                -- "a shipment of"
  quantity                        numeric not null check (quantity > 0),  -- in the good's unit of measure
  shipment_contents_description   text,
  in_response_to_shipment_item_id integer references shipment_item,       -- "in response to"
  check (in_response_to_shipment_item_id <> shipment_item_id)
);

-- SHIPMENT STATUS: what actually happened, and when. The book draws no id:
-- shipment + status type identify it (two bars), so a shipment has one
-- status of each type (point 6). Surrogate key; the identifier is a
-- data-quality query. SHIPMENT STATUS TYPE becomes a SHIPMENT_STATUS group
-- in Ch 2's shared status_type, beside Ch 4's order statuses (point 7).
create table shipment_status (
  shipment_status_id integer generated by default as identity primary key,
  shipment_id        integer     not null references shipment,      -- "the history for"
  status_type_id     text        not null references status_type,   -- "defined using"
  status_datetime    timestamptz not null                           -- STATUS DATE: times allowed, as the text says
);

-- ============================================================
-- Fig 5.3 — Shipment-to-order relationship
-- ============================================================
-- ORDER SHIPMENT: how much of an order line (Ch 4) went out on a shipment
-- line. Many to many, with a quantity, so an order line can ship in parts
-- and a shipment line can fill lines of several orders. The book draws no
-- id: the two barred lines identify it (NOTES, point 11). Surrogate key; the
-- pair twice is a data-quality query, and so are the rules the text leaves
-- to business processes (the same good, the same destination, no more than
-- the shipment line carries) and the direction (point 15).
create table order_shipment (
  order_shipment_id integer generated by default as identity primary key,
  order_item_id     integer not null references order_item,       -- "the shipment of"
  shipment_item_id  integer not null references shipment_item,    -- "shipped via"
  quantity          numeric not null check (quantity > 0)
);

-- SHIPMENT ITEM FEATURE: the features a shipment line actually went out with,
-- to set beside what its order lines asked for (point 16). No attributes;
-- the pair twice is the data-quality query above.
create table shipment_item_feature (
  shipment_item_feature_id integer generated by default as identity primary key,
  shipment_item_id         integer not null references shipment_item,     -- "for"
  product_feature_id       integer not null references product_feature    -- "of"
);

-- ============================================================
-- Fig 5.4 — Shipment receipt for incoming shipments
-- ============================================================
-- SHIPMENT PACKAGE: a box, a carton, a pallet. No line to SHIPMENT is drawn
-- (NOTES, point 17): a package's shipment follows from its contents, and
-- contents from two shipments in one package are a data-quality query.
create table shipment_package (
  shipment_package_id integer generated by default as identity primary key,
  date_created        date not null
);

-- PACKAGING CONTENT: how much of a shipment line sits in a package. Many to
-- many, with a quantity: a line spread over boxes, a box holding lines. The
-- book identifies it by both lines (bars); surrogate key, the pair twice is
-- a data-quality query.
create table packaging_content (
  packaging_content_id integer generated by default as identity primary key,
  shipment_package_id  integer not null references shipment_package,   -- "in"
  shipment_item_id     integer not null references shipment_item,      -- "of"
  quantity             numeric not null check (quantity > 0)
);

create table rejection_reason (
  rejection_reason_id text primary key,   -- REJECTION ID
  description         text not null
);

-- SHIPMENT RECEIPT: one good counted out of one incoming package, accepted
-- or rejected. Only the package is mandatory (point 22). The order line is
-- what the count is checked against; that it agrees with ORDER SHIPMENT,
-- the long way round, is a data-quality query (point 23), and so are the
-- quantities against the package and the reason against the rejection.
create table shipment_receipt (
  shipment_receipt_id integer generated by default as identity primary key,   -- RECEIPT ID
  shipment_package_id integer     not null references shipment_package,     -- "within"
  product_id          integer     references good,                          -- "of"
  inventory_item_id   integer     references inventory_item,                -- "stored into"
  order_item_id       integer     references order_item,                    -- "verified against and applied to"
  rejection_reason_id text        references rejection_reason,              -- "rejected because of"
  datetime_received   timestamptz not null,
  item_description    text        not null,                                 -- what the receiver wrote down
  quantity_accepted   numeric     not null check (quantity_accepted >= 0),
  quantity_rejected   numeric     not null check (quantity_rejected >= 0)
);

-- SHIPMENT RECEIPT ROLE: who received, inspected, signed (a scoped role, as
-- 4.3's ORDER ROLE). Its type is a lookup of its own (point 25). The book's
-- identifier (receipt, type, party: three bars) is a data-quality query.
create table shipment_receipt_role_type (
  shipment_receipt_role_type_id text primary key,
  description                   text not null
);

create table shipment_receipt_role (
  shipment_receipt_role_id      integer generated by default as identity primary key,
  shipment_receipt_id           integer not null references shipment_receipt,             -- "for"
  party_id                      integer not null references party,                        -- "of"
  shipment_receipt_role_type_id text    not null references shipment_receipt_role_type    -- "described by"
);

-- A helper, no book entity: the shipment of each package, worked out from
-- its contents (one row per package and shipment, so a mixed package shows
-- twice).
create view shipment_package_shipment as
select distinct pc.shipment_package_id, si.shipment_id
from packaging_content pc
join shipment_item si on si.shipment_item_id = pc.shipment_item_id;

-- ============================================================
-- Fig 5.5 — Item issuance for outgoing shipments
-- ============================================================
-- PICKLIST: a warehouse sheet, pull these quantities from these stocks. No
-- line to a shipment, a facility or a party (NOTES, point 33): its
-- shipments come through the issuances made according to it.
create table picklist (
  picklist_id  integer generated by default as identity primary key,
  date_created date not null
);

-- PICKLIST ITEM: the plan for one stock. The book identifies it by picklist
-- and inventory item (bars); surrogate key, the pair twice is a data-quality
-- query.
create table picklist_item (
  picklist_item_id  integer generated by default as identity primary key,
  picklist_id       integer not null references picklist,         -- "part of"
  inventory_item_id integer not null references inventory_item,   -- "picked from"
  quantity          numeric not null check (quantity > 0)
);

-- ITEM ISSUANCE: stock pulled out of one inventory item, the receipt's
-- mirror. Usually for a shipment line, not always (point 29). No line to a
-- package (point 27). Its stock against its picklist item's, its good
-- against its line's, its total against the line, its shipment's direction
-- and origin, and the quantity on hand it leaves behind are data-quality
-- queries.
create table item_issuance (
  item_issuance_id  integer generated by default as identity primary key,
  inventory_item_id integer     not null references inventory_item,   -- "issued from"
  shipment_item_id  integer     references shipment_item,             -- "issued for"
  picklist_item_id  integer     references picklist_item,             -- "issued according to"
  issued_datetime   timestamptz not null,
  quantity          numeric     not null check (quantity > 0)
);

-- ITEM ISSUANCE ROLE: who pulled or approved it, scoped to one issuance. Its
-- type is a lookup of its own (point 31). The book's identifier (issuance,
-- type, party) is a data-quality query.
create table item_issuance_role_type (
  item_issuance_role_type_id text primary key,
  description                text not null
);

create table item_issuance_role (
  item_issuance_role_id      integer generated by default as identity primary key,
  item_issuance_id           integer not null references item_issuance,             -- "for"
  party_id                   integer not null references party,                     -- "of"
  item_issuance_role_type_id text    not null references item_issuance_role_type    -- "described by"
);

-- ============================================================
-- Fig 5.6 — Shipping documents
-- ============================================================
-- DOCUMENT TYPE: the drawn subtypes have no attributes, so they are rows
-- here (NOTES, point 35), under a SHIPPING_DOCUMENT grouping row.
create table document_type (
  document_type_id text primary key,
  parent_type_id   text references document_type,
  description      text not null
);

create table document (
  document_id      integer generated by default as identity primary key,
  document_type_id text not null references document_type,   -- "described by"
  description      text not null
);

-- SHIPPING DOCUMENT: a subtype table, since it carries the lines. All three
-- are optional and no arc is drawn (point 34): naming none, a type that
-- disagrees with the subtype row, or levels that contradict each other are
-- data-quality queries.
create table shipping_document (
  document_id         integer primary key references document,
  shipment_id         integer references shipment,           -- "for"
  shipment_item_id    integer references shipment_item,      -- "for"
  shipment_package_id integer references shipment_package    -- "for"
);

-- ============================================================
-- Fig 5.7 — Shipment route segments
-- ============================================================
create table shipment_method_type (
  shipment_method_type_id text primary key,
  description             text not null
);

-- FIXED ASSET, ahead of Ch 8 (Fig 8.5), which will extend it (NOTES, point
-- 41). VEHICLE has no attributes: a type row.
create table fixed_asset_type (
  fixed_asset_type_id text primary key,
  description         text not null
);

create table fixed_asset (
  fixed_asset_id      integer generated by default as identity primary key,
  fixed_asset_type_id text not null references fixed_asset_type,
  name                text not null
);

-- CARRIER SHIPMENT METHOD: the methods each carrier offers. CARRIER is a
-- party role (a role_type row under ORGANIZATION_ROLE, point 40); that the
-- role is a carrier, and the pair twice, are data-quality queries.
create table carrier_shipment_method (
  carrier_shipment_method_id integer generated by default as identity primary key,
  carrier_party_role_id      integer not null references party_role,             -- "for"
  shipment_method_type_id    text    not null references shipment_method_type    -- "of"
);

-- SHIPMENT ROUTE SEGMENT: one leg of a shipment. The book's id is a number
-- within the shipment (a bar to SHIPMENT, point 39): segment_seq_id beside
-- a surrogate key. The vehicle and both facilities are optional (point 38).
-- Mileage in miles, fuel in gallons (Table 5.11).
create table shipment_route_segment (
  shipment_route_segment_id  integer generated by default as identity primary key,
  shipment_id                integer     not null references shipment,               -- "of"
  segment_seq_id             integer     not null,                                   -- SHIPMENT ROUTE SEGMENT ID
  shipment_method_type_id    text        not null references shipment_method_type,   -- "shipped via"
  carrier_party_role_id      integer     not null references party_role,             -- "shipped by" (a CARRIER)
  fixed_asset_id             integer     references fixed_asset,                     -- "shipped using" (a VEHICLE)
  from_facility_id           integer     references facility,                        -- "from"
  to_facility_id             integer     references facility,                        -- "to"
  estimated_start_datetime   timestamptz,
  estimated_arrival_datetime timestamptz,
  actual_start_datetime      timestamptz,
  actual_arrival_datetime    timestamptz,
  start_mileage              numeric,
  end_mileage                numeric,
  fuel_used                  numeric
);
