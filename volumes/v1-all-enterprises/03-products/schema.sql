-- Vol 1, Chapter 3: Products
-- Built up one figure at a time; each section is headed by the figure it implements.
--
-- Key style (as in Ch 2): every table has a single-column primary key
-- (surrogate integer, or a text code for lookups) and plain foreign keys.
-- Rules a plain FK can't express are data-quality queries in queries.sql.

-- ============================================================
-- Fig 3.1 — Product definition
-- ============================================================
-- A PRODUCT is something the enterprise offers, independent of who supplies
-- it or how many we have on the shelf (those come later in the chapter).
--
-- GOOD and SERVICE are exclusive subtypes with no attributes of their own, so
-- they become a product_kind discriminator instead of two empty tables (same
-- move as party_kind in Ch 2).
--
-- The book's sample ids (PAP192, CNS109) are readable codes. We keep a
-- surrogate product_id; those codes are identifiers and get a home in Fig 3.3.
--
-- The three dates are milestones, not an effectivity period. Like thru_date,
-- the discontinuation dates are exclusive: the first day the product is no
-- longer sold / supported. A data-quality query checks their order.

create table product (
  product_id                   integer generated by default as identity primary key,
  product_kind                 text not null check (product_kind in ('GOOD', 'SERVICE')),
  name                         text not null,
  introduction_date            date,
  sales_discontinuation_date   date,
  support_discontinuation_date date,
  comment                      text
);

-- ============================================================
-- Fig 3.2 — Product category
-- ============================================================
-- Categories are data, not columns: a product can sit in many categories,
-- each period dated, and one of them is flagged primary.
--
-- The PRODUCT CATEGORY subtypes (usage, industry, materials) have no
-- attributes, so they become rows in product_category_type: the "dimension"
-- a category belongs to.
--
-- PRODUCT CATEGORY ROLLUP is many-to-many, so a category can have several
-- parents (Business forms sits under Paper and under Printed materials). The
-- figure shows no dates on the rollup, so there are none here.

create table product_category_type (
  product_category_type_id text primary key,
  description              text not null
);

create table product_category (
  product_category_id      integer generated by default as identity primary key,
  product_category_type_id text not null references product_category_type,
  description              text not null
);

create table product_category_rollup (
  product_category_rollup_id  integer generated by default as identity primary key,
  parent_product_category_id  integer not null references product_category,   -- "made up of"
  child_product_category_id   integer not null references product_category,   -- "part of" / "within"
  check (parent_product_category_id <> child_product_category_id)
);

-- primary_flag: at most one current primary category per product is a rule a
-- plain FK can't hold; a data-quality query checks it.
create table product_category_classification (
  product_category_classification_id integer generated by default as identity primary key,
  product_id                         integer not null references product,
  product_category_id                integer not null references product_category,
  from_date                          date    not null,
  thru_date                          date,
  primary_flag                       boolean not null default false,
  comment                            text,
  check (thru_date is null or thru_date > from_date)
);

-- MARKET INTEREST: which kinds of party (Ch 2's party_type, e.g. an industry
-- or a size band) are interested in which product categories. Knowledge about
-- markets, not about any one customer.
create table market_interest (
  market_interest_id  integer generated by default as identity primary key,
  product_category_id integer not null references product_category,
  party_type_id       text    not null references party_type,
  from_date           date    not null,
  thru_date           date,
  check (thru_date is null or thru_date > from_date)
);

-- Every category paired with each of its ancestors at any depth (the category
-- itself is NOT included). UNION, not UNION ALL, so a cycle in the rollup data
-- stops the walk instead of looping forever; a data-quality query reports it.
create view product_category_ancestor as
with recursive walk (product_category_id, ancestor_id) as (
  select child_product_category_id, parent_product_category_id
  from product_category_rollup
  union
  select w.product_category_id, r.parent_product_category_id
  from walk w
  join product_category_rollup r on r.child_product_category_id = w.ancestor_id
)
select product_category_id, ancestor_id from walk;

-- ============================================================
-- Fig 3.3 — Product identification
-- ============================================================
-- A product can carry many codes: our SKU, the manufacturer's part number, a
-- UPC barcode, an ISBN. Each is a row (type + value), not a column per code.
--
-- The GOOD IDENTIFICATION subtypes (SKU, UPCA, UPCE, ISBN, …) have no
-- attributes, so they are rows in the book's own IDENTIFICATION TYPE table.
--
-- GOOD IDENTIFICATION links to GOOD, not PRODUCT: services carry no codes.
-- That gives GOOD a relationship of its own, so it gets a subtype table
-- sharing product_id (as person shares party_id in Ch 2). product_kind stays
-- as the discriminator; a data-quality query checks the two agree.
--
-- value_pattern is not in the book: a regular expression the codes of that
-- type must match (null = free format). A rule stored as data, checked by a
-- data-quality query.

create table good (
  product_id integer primary key references product
);

create table identification_type (
  identification_type_id text primary key,
  description            text not null,
  value_pattern          text
);

-- The book identifies a row by (product, identification type): one value per
-- type per product. We use a surrogate key; data-quality queries check that
-- rule and that no two products share the same code.
create table good_identification (
  good_identification_id integer generated by default as identity primary key,
  product_id             integer not null references good,
  identification_type_id text    not null references identification_type,
  id_value               text    not null
);

-- ============================================================
-- Fig 3.4 — Product feature
-- ============================================================
-- Features are characteristics or options a product can have (colour, size,
-- brand, a duplex unit, hourly billing). One feature is defined once and
-- reused across products; PRODUCT FEATURE APPLICABILITY says, per product and
-- period, whether it's required, standard, optional or selectable.

-- Units of measure come first: products and dimension features use them.
create table unit_of_measure (
  uom_id       text primary key,
  abbreviation text not null,
  description  text not null
);

-- One row = "1 from-unit equals conversion_factor to-units" (1 REAM = 500 EA).
-- The figure has no identifier of its own beyond the two units; a
-- data-quality query checks that a pair and its reverse agree.
create table unit_of_measure_conversion (
  unit_of_measure_conversion_id integer generated by default as identity primary key,
  from_uom_id                   text    not null references unit_of_measure,   -- "converted from"
  to_uom_id                     text    not null references unit_of_measure,   -- "converted into"
  conversion_factor             numeric not null check (conversion_factor > 0),
  check (from_uom_id <> to_uom_id)
);

-- PRODUCT "measured using" UNIT OF MEASURE: the unit a product is sold and
-- counted in (a ream, a box, an hour). Added to the 3.1 table here, where the
-- book introduces it. Optional, as in the book.
alter table product
  add column uom_id text references unit_of_measure;

create table product_feature_category (
  product_feature_category_id integer generated by default as identity primary key,
  description                 text not null
);

-- The PRODUCT FEATURE subtypes become rows. Only DIMENSION has an attribute
-- (number_specified) and a unit of measure (optional); both live on
-- product_feature as nullable columns, as federal_tax_id_num did on
-- organization in Ch 2, with a data-quality query.
create table product_feature_type (
  product_feature_type_id text primary key,
  description             text not null
);

create table product_feature (
  product_feature_id          integer generated by default as identity primary key,
  product_feature_type_id     text    not null references product_feature_type,
  product_feature_category_id integer references product_feature_category,   -- "categorized by"
  description                 text    not null,
  number_specified            numeric,                                        -- DIMENSION only
  uom_id                      text    references unit_of_measure              -- DIMENSION only: "measured using"
);

-- REQUIRED / STANDARD / OPTIONAL / SELECTABLE: exclusive, no attributes,
-- so rows in a type table.
create table product_feature_applicability_type (
  product_feature_applicability_type_id text primary key,
  description                           text not null
);

create table product_feature_applicability (
  product_feature_applicability_id      integer generated by default as identity primary key,
  product_id                            integer not null references product,
  product_feature_id                    integer not null references product_feature,
  product_feature_applicability_type_id text    not null references product_feature_applicability_type,
  from_date                             date    not null,
  thru_date                             date,
  check (thru_date is null or thru_date > from_date)
);

create table product_feature_interaction_type (
  product_feature_interaction_type_id text primary key,
  description                         text not null
);

-- Read a DEPENDENCY as "choosing product_feature_id needs factor_product_feature_id";
-- an INCOMPATIBILITY as "these two can't be chosen together" (either order).
-- product_id is the context: null = the interaction holds for every product.
create table product_feature_interaction (
  product_feature_interaction_id      integer generated by default as identity primary key,
  product_feature_interaction_type_id text    not null references product_feature_interaction_type,
  product_feature_id                  integer not null references product_feature,   -- "of" / "selected in"
  factor_product_feature_id           integer not null references product_feature,   -- "a factor in"
  product_id                          integer references product,                    -- "applicable within the context of"
  check (product_feature_id <> factor_product_feature_id)
);

-- ============================================================
-- Fig 3.5 — Suppliers and manufacturers of products
-- ============================================================
-- Who makes a product, who can supply it to us, and how much of a good to keep
-- in stock. Suppliers and manufacturers are Ch 2 organizations; facilities and
-- geographic boundaries are Ch 2 tables too.

-- PRODUCT "manufactured by" ORGANIZATION: optional (we may not know, and a
-- service has no manufacturer). Added to the 3.1 table here, in book order.
alter table product
  add column manufacturer_party_id integer references organization;

create table preference_type (
  preference_type_id text primary key,
  description        text not null
);

create table rating_type (
  rating_type_id text primary key,
  description    text not null
);

-- SUPPLIER PRODUCT: "this organization can supply this product, from/thru".
-- The book identifies it by product + supplier + available_from_date; we use
-- a surrogate key and a data-quality query for overlapping periods.
-- standard_lead_time is in days (the book gives no unit).
create table supplier_product (
  supplier_product_id  integer generated by default as identity primary key,
  product_id           integer not null references product,        -- "a valid supplier for"
  supplier_party_id    integer not null references organization,   -- "supplied by"
  available_from_date  date    not null,
  available_thru_date  date,
  standard_lead_time   integer check (standard_lead_time >= 0),
  preference_type_id   text    references preference_type,         -- "further described by"
  rating_type_id       text    references rating_type,             -- "rated by"
  comment              text,
  check (available_thru_date is null or available_thru_date > available_from_date)
);

-- REORDER GUIDELINE: when stock of a good falls to reorder_level, order
-- reorder_quantity. Goods only (services aren't stocked). The guideline may be
-- based on a facility, a geographic boundary and/or an internal organization;
-- all three are optional, so none at all means "everywhere".
-- The internal organization is an organization with a current
-- INTERNAL_ORGANIZATION role (Ch 2), checked by a data-quality query.
create table reorder_guideline (
  reorder_guideline_id           integer generated by default as identity primary key,
  product_id                     integer not null references good,   -- "for"
  geographic_boundary_id         integer references geographic_boundary,
  facility_id                    integer references facility,
  internal_organization_party_id integer references organization,
  from_date                      date    not null,
  thru_date                      date,
  reorder_quantity               numeric check (reorder_quantity > 0),
  reorder_level                  numeric check (reorder_level >= 0),
  check (thru_date is null or thru_date > from_date)
);

-- ============================================================
-- Fig 3.6 — Inventory item storage
-- ============================================================
-- A GOOD is the catalogue description ("Johnson bond paper"); an INVENTORY
-- ITEM is physical stock of it: one serialized copier, or 100 reams sitting in
-- one place, in one state, from one lot.

create table inventory_item_status_type (
  inventory_item_status_type_id text primary key,
  description                   text not null
);

create table lot (
  lot_id          integer generated by default as identity primary key,
  creation_date   date    not null,
  quantity        numeric not null check (quantity > 0),
  expiration_date date
);

create table container_type (
  container_type_id text primary key,
  description       text not null
);

create table container (
  container_id      integer generated by default as identity primary key,
  container_type_id text    not null references container_type,   -- "described by"
  facility_id       integer not null references facility,         -- "located at"
  description       text    not null                              -- not in the book: a label to tell bins apart
);

-- SERIALIZED / NON SERIALIZED are exclusive subtypes with one attribute each,
-- so they become a discriminator plus two nullable columns (as DIMENSION's
-- number did in Fig 3.4); a data-quality query checks the combination.
--
-- The exclusive arc (in a facility OR in a container, never both, never
-- neither) is a single-row rule, so it's a check constraint: num_nonnulls.
create table inventory_item (
  inventory_item_id             integer generated by default as identity primary key,
  inventory_item_kind           text    not null check (inventory_item_kind in ('SERIALIZED', 'NON_SERIALIZED')),
  product_id                    integer not null references good,                         -- "the physical occurrence of"
  inventory_item_status_type_id text    not null references inventory_item_status_type,   -- "in the state of"
  lot_id                        integer references lot,                                   -- "part of" (optional)
  facility_id                   integer references facility,                              -- "located at"     } arc:
  container_id                  integer references container,                             -- "located within" } exactly one
  serial_num                    text,                                                     -- SERIALIZED only
  quantity_on_hand              numeric,                                                  -- NON_SERIALIZED only
  check (num_nonnulls(facility_id, container_id) = 1)
);

create table reason (
  reason_id   text primary key,
  description text not null
);

-- A physical count found a difference: quantity is the signed adjustment
-- (-3 = three reams missing). The book identifies a variance by item +
-- physical_inventory_date; surrogate key here, duplicates are a query.
create table inventory_item_variance (
  inventory_item_variance_id integer generated by default as identity primary key,
  inventory_item_id          integer not null references inventory_item,   -- "an adjustment for"
  physical_inventory_date    date    not null,
  quantity                   numeric not null,
  reason_id                  text    not null references reason,           -- "explained with"
  comment                    text
);

-- ============================================================
-- Fig 3.7 — Standard product pricing
-- ============================================================
-- A price is not a column on product: it is derived from PRICE COMPONENT
-- rows, each one a pricing rule ("bond paper is 42.00", "5% off 100+ reams",
-- "1% off internet sales"). Each "based on" link is an optional condition;
-- null means the rule doesn't care. Pricing an order line = finding every
-- component whose conditions all hold, then combining them (queries.sql).

-- UNIT OF MEASURE gets two subtypes. Like GOOD in Fig 3.3, each has a
-- relationship of its own, so each gets a subtype table sharing uom_id: a
-- plain FK can then insist that a currency is a currency. No discriminator:
-- most units (each, ream, inch) are neither.
create table time_frequency_measure (
  uom_id text primary key references unit_of_measure
);

create table currency_measure (
  uom_id text primary key references unit_of_measure
);

-- Thru values are exclusive, like thru dates: a break from 100 thru 1000
-- covers 100 <= quantity < 1000, so breaks meet without gaps or overlaps.
create table quantity_break (
  quantity_break_id integer generated by default as identity primary key,
  from_quantity     numeric not null check (from_quantity >= 0),
  thru_quantity     numeric,
  check (thru_quantity is null or thru_quantity > from_quantity)
);

-- Amounts of the whole order. The book gives no currency; ours are USD.
create table order_value (
  order_value_id integer generated by default as identity primary key,
  from_amount    numeric not null check (from_amount >= 0),
  thru_amount    numeric,
  check (thru_amount is null or thru_amount > from_amount)
);

create table sale_type (
  sale_type_id text primary key,
  description  text not null
);

-- First subtype set (base price, discount, surcharge, manufacturer's suggested
-- price): no attributes, so rows in a type table.
create table price_component_type (
  price_component_type_id text primary key,
  description             text not null
);

-- Second subtype set (one-time, recurring, utilization): a separate box, so an
-- independent axis (discussion point 1 in NOTES). Two of the three carry
-- something (a "per" unit, a quantity), so it becomes a discriminator plus
-- nullable columns, as in Fig 3.6; a data-quality query checks the combination.
-- Nullable: a ream of paper's base price is no kind of charge.
--
-- price vs percent: a base or suggested price is an amount; a discount or
-- surcharge is an amount or a percent, stored positive (the type says which
-- way it goes). A data-quality query checks this per type.
--
-- product and feature are both optional and may both be set: "the duplex unit
-- costs 250 on the OfficeJet" (unlike Fig 3.8, there is no arc here).
create table price_component (
  price_component_id      integer generated by default as identity primary key,
  price_component_type_id text    not null references price_component_type,
  charge_kind             text    check (charge_kind in ('ONE_TIME', 'RECURRING', 'UTILIZATION')),
  from_date               date    not null,
  thru_date               date,
  price                   numeric check (price >= 0),
  percent                 numeric check (percent > 0 and percent <= 100),
  currency_uom_id         text    references currency_measure,      -- "in the currency of"
  -- what is priced
  product_id              integer references product,               -- "a price defined for"
  product_feature_id      integer references product_feature,       -- "a price defined for"
  pricer_party_id         integer references organization,          -- "specified for" / "the pricer of"
  -- the conditions ("based on"); null = any
  geographic_boundary_id  integer references geographic_boundary,
  party_type_id           text    references party_type,
  product_category_id     integer references product_category,
  quantity_break_id       integer references quantity_break,
  order_value_id          integer references order_value,
  sale_type_id            text    references sale_type,
  -- second subtype set
  per_uom_id              text    references unit_of_measure,       -- RECURRING (a time frequency) or UTILIZATION: "per"
  quantity                numeric check (quantity > 0),             -- UTILIZATION only: per how many units (null = 1)
  comment                 text,
  check (thru_date is null or thru_date > from_date)
);

-- ============================================================
-- Fig 3.8 — Estimated product cost
-- ============================================================
-- What a product (or one feature of it) costs us to make or provide, one
-- dated estimate per cost component: the paper stock, the printing labour,
-- the freight. Margin = price (Fig 3.7) minus the sum of these.

-- The book has both subtypes (materials, labour, other) and a COST COMPONENT
-- TYPE. As with Ch 2's party types, the attribute-less subtypes become the top
-- level of the type hierarchy, and the finer types sit under them (Paper stock
-- under Materials). A data-quality query checks every type rolls up to one of
-- the three.
create table cost_component_type (
  cost_component_type_id text primary key,
  parent_type_id         text references cost_component_type,
  description            text not null
);

-- The book calls the identifier cost_component_id; we follow our
-- <table>_id rule. The exclusive arc (a product OR a feature) is a single-row
-- rule, so it's a check constraint, as in Fig 3.6. The book gives the cost no
-- currency; ours are USD, per unit of the product's unit of measure.
create table estimated_product_cost (
  estimated_product_cost_id integer generated by default as identity primary key,
  product_id                integer references product,                         -- "calculated for" } arc:
  product_feature_id        integer references product_feature,                 -- "calculated for" } exactly one
  cost_component_type_id    text    not null references cost_component_type,    -- "categorized by"
  geographic_boundary_id    integer references geographic_boundary,             -- "specified for" (optional)
  organization_party_id     integer references organization,                    -- "specified for" (optional)
  from_date                 date    not null,
  thru_date                 date,
  cost                      numeric not null check (cost >= 0),
  check (num_nonnulls(product_id, product_feature_id) = 1),
  check (thru_date is null or thru_date > from_date)
);
