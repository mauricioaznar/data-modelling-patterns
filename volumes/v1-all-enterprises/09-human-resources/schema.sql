-- ============================================================
-- Fig 9.2 — Employment
-- ============================================================
-- Nothing new to store: EMPLOYMENT is Ch 2's party_relationship typed
-- EMPLOYMENT (2.6a), from the internal organization's role to the employee's,
-- with 2.7's status. The view names both parties, so later figures
-- (fulfillment, pay, benefits) can ask "who employed whom, when" without the
-- role joins. Ch 2's 2.5 `employment` table is Ch 2's comparison and stays
-- unused (NOTES, point 2).
create view employment_relationship as
select r.party_relationship_id,
       er.party_id          as employer_party_id,
       ee.party_id          as employee_party_id,
       r.from_party_role_id as employer_party_role_id,
       r.to_party_role_id   as employee_party_role_id,
       r.from_date,
       r.thru_date,
       r.status_type_id,
       r.comment
from party_relationship r
join party_role er on er.party_role_id = r.from_party_role_id
join party_role ee on ee.party_role_id = r.to_party_role_id
where r.party_relationship_type_id = 'EMPLOYMENT';

-- ============================================================
-- Fig 9.3 — Position definition
-- ============================================================
-- POSITION TYPE was built ahead in Ch 6 (id, description). 9.3 adds the
-- title, mandatory (Ch 6's three rows take their description, point 10), and
-- the share of benefits the enterprise pays. The update is a migration of
-- Ch 6's rows, so it lives here, before the constraint.
alter table position_type
  add column title           text,
  add column benefit_percent numeric(5, 2) check (benefit_percent between 0 and 100);
update position_type set title = description where title is null;
alter table position_type alter column title set not null;

-- A slot in the enterprise, not a person. Estimated dates: when it is
-- planned; actual dates: when it really opened and closed. The flags describe
-- the slot, so they stay when the holder changes. Funded through a Ch 8
-- budget item, optionally (point 8); "authorized" is derived from that
-- budget's status, not stored.
create table position (
  position_id         integer generated by default as identity primary key,
  position_type_id    text    not null references position_type,   -- "described by"
  budget_item_id      integer references budget_item,              -- "approved thru" (point 8)
  estimated_from_date date    not null,
  estimated_thru_date date,
  salary_flag         boolean not null,   -- salaried, or paid by the hour
  exempt_flag         boolean not null,   -- exempt from overtime rules
  fulltime_flag       boolean not null,
  temporary_flag      boolean not null,
  actual_from_date    date,
  actual_thru_date    date,
  check (estimated_thru_date is null or estimated_thru_date > estimated_from_date),
  check (actual_thru_date is null or (actual_from_date is not null and actual_thru_date > actual_from_date))
);

create table responsibility_type (
  responsibility_type_id text primary key,
  description            text not null
);

-- What a type of job may be given (VALID RESPONSIBILITY) and what one slot is
-- given (POSITION RESPONSIBILITY), both dated. The book keys each on its two
-- parents + from date (tildes): surrogate keys, the triple unique. That a
-- slot's responsibility is valid for its type is the book's data check, a
-- query here.
create table valid_responsibility (
  valid_responsibility_id integer generated by default as identity primary key,
  position_type_id        text not null references position_type,         -- "associated with"
  responsibility_type_id  text not null references responsibility_type,   -- "defined by"
  from_date               date not null,
  thru_date               date,
  comment                 text,
  unique (position_type_id, responsibility_type_id, from_date),
  check (thru_date is null or thru_date > from_date)
);

create table position_responsibility (
  position_responsibility_id integer generated by default as identity primary key,
  position_id                integer not null references position,              -- "associated with"
  responsibility_type_id     text    not null references responsibility_type,   -- "defined by"
  from_date                  date    not null,
  thru_date                  date,
  comment                    text,
  unique (position_id, responsibility_type_id, from_date),
  check (thru_date is null or thru_date > from_date)
);

-- ============================================================
-- Fig 9.4 — Position type definition
-- ============================================================
-- A position type sits in several groupings at once, each dated: the
-- classification pattern again (Ch 2's party classification, Ch 3's product
-- category classification). The book keys it on type + class + from date
-- (tildes): surrogate key, the triple unique. Standard hours per week belong
-- to the classification row (point 11).
create table position_classification_type (
  position_classification_type_id text primary key,
  description                     text not null
);

create table position_type_class (
  position_type_class_id          integer generated by default as identity primary key,
  position_type_id                text not null references position_type,                  -- "for"
  position_classification_type_id text not null references position_classification_type,   -- "defined by"
  from_date                       date not null,
  thru_date                       date,
  standard_hours_per_week         numeric(4, 1) check (standard_hours_per_week > 0 and standard_hours_per_week <= 168),
  unique (position_type_id, position_classification_type_id, from_date),
  check (thru_date is null or thru_date > from_date)
);

-- UNION is an ORGANIZATION ROLE: a role_type row (seed) and a plain FK to the
-- union's party role, optional (dashed). That the role really is a union is
-- a data check (point 14).
alter table position_type
  add column union_party_role_id integer references party_role;   -- "unionized by"

-- ============================================================
-- Fig 9.5 — Position fulfillment
-- ============================================================
-- A slot belongs to a hiring company, drawn as an ORGANIZATION, not an
-- internal organization role (point 16), and is in one state, a current
-- value with no history (point 15). Both drawn mandatory. The states are
-- Ch 2 status types under a POSITION_STATUS group (seed).
alter table position
  add column organization_party_id integer not null references organization,   -- "within"
  add column status_type_id        text    not null references status_type;    -- "in the state of"

-- A person in a slot, dated. A person, not an employee role (point 18); two
-- people may share a slot at once (a job share, point 19), so no check
-- against overlaps. The book keys it on position + person + from date
-- (tildes): surrogate key, the triple unique.
create table position_fulfillment (
  position_fulfillment_id integer generated by default as identity primary key,
  position_id             integer not null references position,   -- "the fulfillment of"
  party_id                integer not null references person,     -- "accepted by"
  from_date               date    not null,
  thru_date               date,
  comment                 text,
  unique (position_id, party_id, from_date),
  check (thru_date is null or thru_date > from_date)
);

-- ============================================================
-- Fig 9.6 — Position reporting relationships
-- ============================================================
-- Slots report to slots, dated, so the chart stands when a box is empty and
-- a reorganization closes rows instead of editing people. Two lines to
-- POSITION: the slot reporting and the slot managing it. A slot may report
-- to several managers at once (matrix); the primary flag marks the line it
-- ultimately reports through. One primary at a time is a data check (point
-- 23). The book keys it on both slots + from date (tildes): surrogate key,
-- the triple unique.
create table position_reporting_structure (
  position_reporting_structure_id integer generated by default as identity primary key,
  reporting_position_id           integer not null references position,   -- "the reports to structure" for the slot reporting
  manager_position_id             integer not null references position,   -- "managed by"
  from_date                       date    not null,
  thru_date                       date,
  comment                         text,
  primary_flag                    boolean not null,
  unique (reporting_position_id, manager_position_id, from_date),
  check (reporting_position_id <> manager_position_id),
  check (thru_date is null or thru_date > from_date)
);

-- ============================================================
-- Fig 9.7 — Salary determination and history
-- ============================================================
-- PERIOD TYPE is Ch 8's (YEAR, MONTH, the fiscal ones); 9.7 prices pay per
-- period, so it gains HOUR here, needed before Ch 6's hourly rows can take it.
insert into period_type (period_type_id, description) values
  ('HOUR', 'Hour');

-- A grade is a ladder of steps; each step's amount is a current value,
-- updated in place when the whole grade gets a raise (date modified, no
-- history, point 30). The book keys a step on grade + seq (tilde): surrogate
-- key, the pair unique.
create table pay_grade (
  pay_grade_id integer primary key,
  name         text not null,
  comment      text
);

create table salary_step (
  salary_step_id     integer generated by default as identity primary key,
  pay_grade_id       integer not null references pay_grade,   -- "part of"
  salary_step_seq_id integer not null,
  amount             numeric(12, 2) not null check (amount > 0),
  date_modified      date not null,
  unique (pay_grade_id, salary_step_seq_id)
);

-- POSITION TYPE RATE was built in Ch 6 (type, rate type, dated, a rate).
-- 9.7 adds the period the rate is for (part of the key, the text says) and
-- an optional salary step: a rate is an amount, or a step of a pay grade,
-- never both (the book's business rule; one row, one rule: a check
-- constraint). Ch 6's rows are hourly. Rate type joins the key (point 26):
-- surrogate key, the four unique.
alter table position_type_rate
  add column period_type_id text references period_type,                -- "for" (tilde)
  add column salary_step_id integer references salary_step,             -- "associated with"
  alter column rate drop not null;
update position_type_rate set period_type_id = 'HOUR' where period_type_id is null;
alter table position_type_rate
  alter column period_type_id set not null,
  add constraint position_type_rate_amount_or_step check (num_nonnulls(rate, salary_step_id) = 1),
  add constraint position_type_rate_key unique (position_type_id, rate_type_id, period_type_id, from_date);

-- What a person was actually paid, on the employment (Ch 2's party
-- relationship, the EMPLOYMENT row): a check keeps it to employments, and
-- the text's contractor variant would just drop that check. Optionally
-- described by the step it was set from. The book keys it on employment +
-- from date (tilde): surrogate key, the pair unique.
create table pay_history (
  pay_history_id        integer generated by default as identity primary key,
  party_relationship_id integer not null references party_relationship,   -- "the record for" an EMPLOYMENT
  period_type_id        text    not null references period_type,          -- "for"
  salary_step_id        integer references salary_step,                   -- "associated with"
  from_date             date    not null,
  thru_date             date,
  amount                numeric(12, 2) not null check (amount > 0),
  comment               text,
  unique (party_relationship_id, from_date),
  check (thru_date is null or thru_date > from_date)
);

-- ============================================================
-- Fig 9.8 — Benefits tracking
-- ============================================================
-- BENEFIT TYPE carries the standard share the employer pays; PARTY BENEFIT is
-- one employment's benefit of one type for a while: its cost per period, the
-- share actually paid, and the time off available (vacation, sick days).
-- On the employment (Ch 2's party relationship), as pay history; a check
-- keeps it to employments. The book keys it on employment + benefit type +
-- from date (tildes): surrogate key, the triple unique.
create table benefit_type (
  benefit_type_id          text primary key,
  name                     text not null,
  description              text not null,
  employer_paid_percentage numeric(5, 2) check (employer_paid_percentage between 0 and 100)
);

create table party_benefit (
  party_benefit_id             integer generated by default as identity primary key,
  party_relationship_id        integer not null references party_relationship,   -- "the benefits for" an EMPLOYMENT
  benefit_type_id              text    not null references benefit_type,         -- "defined by"
  period_type_id               text    not null references period_type,          -- "further defined by" (point 33)
  from_date                    date    not null,
  thru_date                    date,
  cost                         numeric(12, 2) check (cost >= 0),
  actual_employer_paid_percent numeric(5, 2) check (actual_employer_paid_percent between 0 and 100),
  available_time               numeric(6, 2) check (available_time >= 0),
  unique (party_relationship_id, benefit_type_id, from_date),
  check (thru_date is null or thru_date > from_date)
);

-- ============================================================
-- Fig 9.9 — Payroll information
-- ============================================================
create table deduction_type (
  deduction_type_id text primary key,
  description       text not null
);

-- How an employee wants to be paid by one employer: a share or a flat
-- amount into an account by a payment method, or a standing deduction of a
-- type per period. Keyed, the text says, on a sequence within the employee's
-- role and the internal organization's (the hiring firm), not on the
-- employment (point 37): surrogate key, the triple unique. Which columns a
-- row fills depends on its kind; nothing in the drawing says which (point
-- 38). That the shares on a day add up to no more than 100 is a check.
create table payroll_preference (
  payroll_preference_id                integer generated by default as identity primary key,
  employee_party_role_id               integer not null references party_role,      -- "for" an EMPLOYEE
  internal_organization_party_role_id  integer not null references party_role,      -- "of" an INTERNAL ORGANIZATION
  payroll_preference_seq_id            integer not null,
  from_date                            date    not null,
  thru_date                            date,
  percentage                           numeric(5, 2) check (percentage > 0 and percentage <= 100),
  flat_amount                          numeric(12, 2) check (flat_amount > 0),
  routing_number                       text,
  account_number                       text,
  bank_name                            text,
  period_type_id                       text references period_type,                 -- "defined by"
  payment_method_type_id               text references payment_method_type,         -- "defined by"
  deduction_type_id                    text references deduction_type,              -- "defined by"
  unique (employee_party_role_id, internal_organization_party_role_id, payroll_preference_seq_id),
  check (thru_date is null or thru_date > from_date)
);

-- PAYCHECK is a DISBURSEMENT (Ch 7's payment, payment_kind DISBURSEMENT)
-- with two lines of its own, so a subtype table sharing the payment's key:
-- issued for an employee role, from an internal organization role. That
-- they match the payment's to and from parties is a check. The payment's
-- amount is the gross pay; the net is derived (point 35).
create table paycheck (
  payment_id                          integer primary key references payment,
  employee_party_role_id              integer not null references party_role,   -- "issued for"
  internal_organization_party_role_id integer not null references party_role    -- "issued from"
);

-- What came off one paycheck. The book keys it on the paycheck + a deduction
-- id (tilde; its line runs through PAYMENT into PAYCHECK, point 34):
-- surrogate key, the pair unique.
create table deduction (
  deduction_id      integer generated by default as identity primary key,
  payment_id        integer not null references paycheck,         -- "a reduction of"
  deduction_seq_id  integer not null,                             -- the book's deduction id
  deduction_type_id text    not null references deduction_type,   -- "defined by"
  amount            numeric(12, 2) not null check (amount > 0),
  unique (payment_id, deduction_seq_id)
);

