-- ============================================================
-- Fig 9.12a — Employee performance
-- ============================================================
-- The alternate 9.12b (reviews and notes as Ch 2 communication event
-- purposes) is not built: 9.14 keeps 9.12a.
--
-- A review is for an EMPLOYEE role, from a MANAGER role (Ch 2 party roles,
-- plain FKs; the role types are a check), over a period. What it led to is
-- three optional lines: the pay record it set, a bonus paycheck, a new slot.
-- RATING TYPE is Ch 3's (supplier ratings): the same entity, more rows.
create table perf_review_item_type (
  perf_review_item_type_id text primary key,
  description              text not null
);

create table performance_note_type (
  performance_note_type_id text primary key,
  description              text not null
);

create table performance_review (
  performance_review_id  integer generated by default as identity primary key,   -- the book's perf review id
  employee_party_role_id integer not null references party_role,    -- "for" an EMPLOYEE
  manager_party_role_id  integer not null references party_role,    -- "from" a MANAGER
  from_date              date    not null,
  thru_date              date,
  comments               text,
  pay_history_id         integer references pay_history,            -- "affecting"
  payment_id             integer references paycheck,               -- "resulting in a bonus of"
  position_id            integer references position,               -- "resulting in"
  check (thru_date is null or thru_date > from_date)
);

-- The book keys an item on its review + a seq (tilde): surrogate key, the
-- pair unique. Both types drawn mandatory.
create table performance_review_item (
  performance_review_item_id integer generated by default as identity primary key,
  performance_review_id      integer not null references performance_review,      -- "part of"
  perf_review_seq_id         integer not null,
  perf_review_item_type_id   text    not null references perf_review_item_type,   -- "described by"
  rating_type_id             text    not null references rating_type,             -- "scored using"
  comment                    text,
  unique (performance_review_id, perf_review_seq_id)
);

-- A note between reviews: about an employee, from a manager, typed, dated.
-- The book keys it on employee + manager + type + from date (tildes):
-- surrogate key, the four unique.
create table performance_note (
  performance_note_id      integer generated by default as identity primary key,
  employee_party_role_id   integer not null references party_role,              -- "regarding the performance of"
  manager_party_role_id    integer not null references party_role,              -- "given by"
  performance_note_type_id text    not null references performance_note_type,   -- "described by"
  from_date                date    not null,
  thru_date                date,
  communication_date       date,
  comment                  text,
  unique (employee_party_role_id, manager_party_role_id, performance_note_type_id, from_date),
  check (thru_date is null or thru_date > from_date)
);
