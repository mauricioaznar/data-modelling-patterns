-- ============================================================
-- Fig 9.11 — Employee skills and qualifications
-- ============================================================
-- What a party can show, not what it was hired for. Qualifications, skills
-- and resumes belong to any PARTY (a firm can be certified); training to a
-- PERSON. CERTIFICATION and DEGREE are attribute-less subtypes of PARTY
-- QUALIFICATION: rows in a qualification_type hierarchy (two groups), not
-- tables. A held qualification uses a type under a group, never the group.
create table qualification_type (
  qualification_type_id text primary key,
  parent_type_id        text references qualification_type,
  description           text not null
);

-- The book keys it on party + type (tildes) with from date mandatory but not
-- in the key: a renewed certification would be a second row, so the date
-- joins the unique (point 42).
create table party_qualification (
  party_qualification_id integer generated by default as identity primary key,
  party_id               integer not null references party,                -- "held by"
  qualification_type_id  text    not null references qualification_type,   -- "described by"
  from_date              date    not null,
  thru_date              date,
  unique (party_id, qualification_type_id, from_date),
  check (thru_date is null or thru_date > from_date)
);

