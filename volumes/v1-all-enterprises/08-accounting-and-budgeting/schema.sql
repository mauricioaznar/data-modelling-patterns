-- Vol 1, Chapter 8: Accounting and Budgeting
-- Built up one figure at a time; each section is headed by the figure it implements.

-- ============================================================
-- Fig 8.1 — Chart of accounts for internal organizations
-- ============================================================
-- The chart is the enterprise's: GENERAL LEDGER ACCOUNT keyed on the
-- account number the accountants use (110 cash, 120 receivables), so the
-- seed keeps the book's numbers. Which internal organization keeps which
-- account, and when, is ORGANIZATION GL ACCOUNT. Like Ch 3, the organization
-- is a plain FK to organization; that it is an INTERNAL_ORGANIZATION (Ch 2)
-- is a data-quality query.

create table general_ledger_account_type (
  general_ledger_account_type_id text primary key,   -- ASSET, LIABILITY, OWNERS_EQUITY, REVENUE, EXPENSE
  description                    text not null
);

create table general_ledger_account (
  general_ledger_account_id      integer primary key,   -- the account number: 110, 120...
  general_ledger_account_type_id text    not null references general_ledger_account_type,   -- "defined by"
  name                           text    not null,
  description                    text    not null
);

-- The book identifies it by its two parents (tildes); surrogate key here,
-- and the same account twice for one organization at once is a query.
create table organization_gl_account (
  organization_gl_account_id     integer generated by default as identity primary key,
  internal_organization_party_id integer not null references organization,            -- "for"
  general_ledger_account_id      integer not null references general_ledger_account,  -- "for"
  from_date                      date    not null,
  thru_date                      date,
  check (thru_date is null or thru_date > from_date)
);

create table period_type (
  period_type_id text primary key,   -- FISCAL_YEAR, FISCAL_QUARTER, FISCAL_MONTH
  description    text not null
);

-- A period belongs to one organization (fiscal years differ) and may sit
-- "within" a bigger one: months in quarters in years. That the parent is the
-- same organization's and contains it is a query. thru_date is exclusive,
-- like every other thru_date here, and mandatory: a period always ends.
create table accounting_period (
  accounting_period_id           integer generated by default as identity primary key,
  internal_organization_party_id integer not null references organization,        -- "for"
  period_type_id                 text    not null references period_type,         -- "defined by"
  within_accounting_period_id    integer references accounting_period,            -- "within"
  acctg_period_num               integer not null,   -- 2001 for a year, 1-4 for a quarter
  from_date                      date    not null,
  thru_date                      date    not null,
  check (thru_date > from_date)
);

-- ============================================================
-- Fig 8.2 — Accounting transactions
-- ============================================================
-- The book's subtype tree (INTERNAL: depreciation, variances...; EXTERNAL:
-- obligations and payments) has no attributes of its own, so it becomes the
-- top rows of ACCOUNTING TRANSACTION TYPE, and the book's finer types
-- (Table 8.3's "payment receipt for invoices") hang under their subtype
-- (NOTES, point 12). INTERNAL, EXTERNAL, OBLIGATION and PAYMENT are grouping
-- rows, never used on a transaction (a query).

create table accounting_transaction_type (
  accounting_transaction_type_id text primary key,
  parent_type_id                 text references accounting_transaction_type,
  description                    text not null
);

-- Each type with the book's subtype it falls under: root_id INTERNAL or
-- EXTERNAL, subtype_id the leaf of the book's tree (DEPRECIATION, SALES,
-- RECEIPT...; null for a grouping row), external_group_id OBLIGATION or PAYMENT.
create view accounting_transaction_type_class as
with recursive up as (
  select t.accounting_transaction_type_id as type_id, t.accounting_transaction_type_id as ancestor_id,
         t.parent_type_id as ancestor_parent_id
  from accounting_transaction_type t
  union all
  select u.type_id, p.accounting_transaction_type_id, p.parent_type_id
  from up u join accounting_transaction_type p on p.accounting_transaction_type_id = u.ancestor_parent_id
)
select type_id,
       max(ancestor_id) filter (where ancestor_parent_id is null)                                 as root_id,
       max(ancestor_id) filter (where ancestor_parent_id in ('INTERNAL', 'OBLIGATION', 'PAYMENT')) as subtype_id,
       max(ancestor_id) filter (where ancestor_id in ('OBLIGATION', 'PAYMENT'))                   as external_group_id
from up
group by type_id;

-- The subtypes' lines become nullable columns, checked against the type by
-- queries. One from_party_id serves both "from" lines (Table 8.3 shows them
-- in one column): for an internal transaction it is the internal
-- organization affected, for an external one the sender. to_party_id is the
-- external receiver. The source document is at most one of three, and only
-- on its own subtype (a query): an invoice for SALES, a payment for RECEIPT
-- or DISBURSEMENT, a count's variance for ITEM_VARIANCE. No amount: a
-- transaction is worth its debits (Fig 8.3a; NOTES, point 3).
create table accounting_transaction (
  accounting_transaction_id      integer generated by default as identity primary key,
  accounting_transaction_type_id text    not null references accounting_transaction_type,   -- "described by"
  from_party_id                  integer not null references party,     -- "from": affected organization, or sender
  to_party_id                    integer references party,              -- "to": receiver, external only
  invoice_id                     integer references invoice,            -- SALES "originated from"
  payment_id                     integer references payment,            -- PAYMENT "originated from"
  inventory_item_variance_id     integer references inventory_item_variance,   -- ITEM VARIANCE "originated from"
  transaction_date               date    not null,   -- when it happened
  entry_date                     date    not null,   -- when it was booked
  description                    text    not null,
  check (from_party_id <> to_party_id),
  check (num_nonnulls(invoice_id, payment_id, inventory_item_variance_id) <= 1)
);
