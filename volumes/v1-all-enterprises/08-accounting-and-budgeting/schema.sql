-- Vol 1, Chapter 8: Accounting and Budgeting
-- Built up one figure at a time; each section is headed by the figure it implements.

-- ============================================================
-- Fig 8.1 — Chart of accounts for internal organizations
-- ============================================================
-- The chart is the enterprise's: GENERAL LEDGER ACCOUNT keyed on the
-- account number the accountants use (110 cash, 120 receivables), so the
-- seed keeps the book's numbers. Which internal organization keeps which
-- account, and when, is ORGANIZATION GL ACCOUNT. Like Ch 3, the organization
-- is a plain FK to organization; that it is an INTERNAL_ORGANIZATION (Ch 2)
-- is a data-quality query.

create table general_ledger_account_type (
  general_ledger_account_type_id text primary key,   -- ASSET, LIABILITY, OWNERS_EQUITY, REVENUE, EXPENSE
  description                    text not null
);

create table general_ledger_account (
  general_ledger_account_id      integer primary key,   -- the account number: 110, 120...
  general_ledger_account_type_id text    not null references general_ledger_account_type,   -- "defined by"
  name                           text    not null,
  description                    text    not null
);

-- The book identifies it by its two parents (tildes); surrogate key here,
-- and the same account twice for one organization at once is a query.
create table organization_gl_account (
  organization_gl_account_id     integer generated by default as identity primary key,
  internal_organization_party_id integer not null references organization,            -- "for"
  general_ledger_account_id      integer not null references general_ledger_account,  -- "for"
  from_date                      date    not null,
  thru_date                      date,
  check (thru_date is null or thru_date > from_date)
);

create table period_type (
  period_type_id text primary key,   -- FISCAL_YEAR, FISCAL_QUARTER, FISCAL_MONTH
  description    text not null
);

-- A period belongs to one organization (fiscal years differ) and may sit
-- "within" a bigger one: months in quarters in years. That the parent is the
-- same organization's and contains it is a query. thru_date is exclusive,
-- like every other thru_date here, and mandatory: a period always ends.
create table accounting_period (
  accounting_period_id           integer generated by default as identity primary key,
  internal_organization_party_id integer not null references organization,        -- "for"
  period_type_id                 text    not null references period_type,         -- "defined by"
  within_accounting_period_id    integer references accounting_period,            -- "within"
  acctg_period_num               integer not null,   -- 2001 for a year, 1-4 for a quarter
  from_date                      date    not null,
  thru_date                      date    not null,
  check (thru_date > from_date)
);

-- ============================================================
-- Fig 8.2 — Accounting transactions
-- ============================================================
-- The book's subtype tree (INTERNAL: depreciation, variances...; EXTERNAL:
-- obligations and payments) has no attributes of its own, so it becomes the
-- top rows of ACCOUNTING TRANSACTION TYPE, and the book's finer types
-- (Table 8.3's "payment receipt for invoices") hang under their subtype
-- (NOTES, point 12). INTERNAL, EXTERNAL, OBLIGATION and PAYMENT are grouping
-- rows, never used on a transaction (a query).

create table accounting_transaction_type (
  accounting_transaction_type_id text primary key,
  parent_type_id                 text references accounting_transaction_type,
  description                    text not null
);

-- Each type with the book's subtype it falls under: root_id INTERNAL or
-- EXTERNAL, subtype_id the leaf of the book's tree (DEPRECIATION, SALES,
-- RECEIPT...; null for a grouping row), external_group_id OBLIGATION or PAYMENT.
create view accounting_transaction_type_class as
with recursive up as (
  select t.accounting_transaction_type_id as type_id, t.accounting_transaction_type_id as ancestor_id,
         t.parent_type_id as ancestor_parent_id
  from accounting_transaction_type t
  union all
  select u.type_id, p.accounting_transaction_type_id, p.parent_type_id
  from up u join accounting_transaction_type p on p.accounting_transaction_type_id = u.ancestor_parent_id
)
select type_id,
       max(ancestor_id) filter (where ancestor_parent_id is null)                                 as root_id,
       max(ancestor_id) filter (where ancestor_parent_id in ('INTERNAL', 'OBLIGATION', 'PAYMENT')) as subtype_id,
       max(ancestor_id) filter (where ancestor_id in ('OBLIGATION', 'PAYMENT'))                   as external_group_id
from up
group by type_id;

-- The subtypes' lines become nullable columns, checked against the type by
-- queries. One from_party_id serves both "from" lines (Table 8.3 shows them
-- in one column): for an internal transaction it is the internal
-- organization affected, for an external one the sender. to_party_id is the
-- external receiver. The source document is at most one of three, and only
-- on its own subtype (a query): an invoice for SALES, a payment for RECEIPT
-- or DISBURSEMENT, a count's variance for ITEM_VARIANCE. No amount: a
-- transaction is worth its debits (Fig 8.3a; NOTES, point 3).
create table accounting_transaction (
  accounting_transaction_id      integer generated by default as identity primary key,
  accounting_transaction_type_id text    not null references accounting_transaction_type,   -- "described by"
  from_party_id                  integer not null references party,     -- "from": affected organization, or sender
  to_party_id                    integer references party,              -- "to": receiver, external only
  invoice_id                     integer references invoice,            -- SALES "originated from"
  payment_id                     integer references payment,            -- PAYMENT "originated from"
  inventory_item_variance_id     integer references inventory_item_variance,   -- ITEM VARIANCE "originated from"
  transaction_date               date    not null,   -- when it happened
  entry_date                     date    not null,   -- when it was booked
  description                    text    not null,
  check (from_party_id <> to_party_id),
  check (num_nonnulls(invoice_id, payment_id, inventory_item_variance_id) <= 1)
);

-- ============================================================
-- Fig 8.3a — Accounting transaction details
-- ============================================================
-- Double entry: each detail is one posting, a debit or a credit of an
-- amount to one organization's account. The book keys a detail on its
-- transaction + seq id; surrogate key here, so "associated with" (the
-- payment's credit that settles an invoice's debit) is a plain FK. That a
-- transaction balances, posts to accounts open that day, and only to the
-- books of its own organizations are queries. "Allocated to" is not null
-- though the line looks dashed (NOTES, point 7); the flag is kept rather
-- than a signed amount (point 8).
create table transaction_detail (
  transaction_detail_id                 integer generated by default as identity primary key,
  accounting_transaction_id             integer not null references accounting_transaction,    -- "part of"
  trans_detail_seq_id                   integer not null,
  organization_gl_account_id            integer not null references organization_gl_account,   -- "allocated to"
  amount                                numeric not null check (amount > 0),   -- USD
  debit_credit_flag                     text    not null check (debit_credit_flag in ('DEBIT', 'CREDIT')),
  associated_with_transaction_detail_id integer references transaction_detail,                 -- "associated with"
  check (associated_with_transaction_detail_id <> transaction_detail_id)
);

-- ============================================================
-- Fig 8.3b — Accounting transaction detail with account balances
-- ============================================================
-- An organization's account balance for one period, stored: derived data,
-- kept for closed periods so reports don't re-add years of postings. Built
-- as an add-on (NOTES, point 9): the detail still posts to the account
-- (8.3a's line), and a query checks each stored balance against its
-- details. amount is debits − credits, like the trial balance. One balance
-- per account per period (the book's key) is a unique constraint.
create table organization_gl_account_balance (
  organization_gl_account_balance_id integer generated by default as identity primary key,
  organization_gl_account_id         integer not null references organization_gl_account,   -- "of"
  accounting_period_id               integer not null references accounting_period,         -- "within"
  amount                             numeric not null,   -- debits − credits, USD
  unique (organization_gl_account_id, accounting_period_id)
);

-- ============================================================
-- Fig 8.4 — General ledger account associations and subsidiary ledger accounts
-- ============================================================
-- A control account (receivables) breaks down into subsidiary accounts (per
-- customer), to any depth: the recursion. A subsidiary row keeps its
-- parent's organization and GL account number, narrowed to what it is about
-- (NOTES, point 14): a supplier or bill-to customer (Ch 2 party roles), a
-- product or a product category (Ch 3). All optional, no arc drawn (point
-- 13). Same organization, same number and dates inside the parent's are a
-- query, as is the role behind each party-role reference.
alter table organization_gl_account
  add column subsidiary_of_organization_gl_account_id integer references organization_gl_account,   -- "a subsidiary account of"
  add column supplier_party_role_id                   integer references party_role,                -- "referencing" SUPPLIER
  add column bill_to_customer_party_role_id           integer references party_role,                -- "referencing" BILL TO CUSTOMER
  add column product_category_id                      integer references product_category,          -- "referencing"
  add column product_id                               integer references product,                   -- "referencing"
  add check (subsidiary_of_organization_gl_account_id <> organization_gl_account_id);

-- ============================================================
-- Fig 8.5 — Asset depreciation
-- ============================================================
-- DEPRECIATION, one of 8.2's internal subtypes, gets its own line: the fixed
-- asset it depreciates. A nullable column on accounting_transaction, like
-- the source documents; that a depreciation has one and nothing else does
-- is a query. FIXED ASSET is Ch 5's, with Ch 6's columns; its subtypes are
-- already fixed_asset_type rows (PROPERTY, VEHICLE, EQUIPMENT, OTHER).
-- date_acquired stays nullable though starred (NOTES, point 16).
alter table accounting_transaction
  add column fixed_asset_id integer references fixed_asset;   -- DEPRECIATION "for"

-- The method is a lookup with a formula kept as text: a description for
-- the accountants, not something the database runs.
create table depreciation_method (
  depreciation_method_id text primary key,   -- STRAIGHT_LINE, DOUBLE_DECLINING_BALANCE...
  description            text not null,
  formula                text
);

-- Which method each asset is depreciated by, and when. The book identifies
-- it by both parents (tildes); surrogate key, and two methods on one asset
-- at once is a query.
create table fixed_asset_depreciation_method (
  fixed_asset_depreciation_method_id integer generated by default as identity primary key,
  fixed_asset_id                     integer not null references fixed_asset,           -- "for"
  depreciation_method_id             text    not null references depreciation_method,   -- "defined by"
  from_date                          date    not null,
  thru_date                          date,
  check (thru_date is null or thru_date > from_date)
);

-- ============================================================
-- Fig 8.6 — Budget definition
-- ============================================================
-- STANDARD TIME PERIOD: a calendar period (the year 2001, June 2002) with no
-- organization, typed by 8.1's PERIOD TYPE. Kept apart from accounting_period
-- (NOTES, point 19).
create table standard_time_period (
  standard_time_period_id integer generated by default as identity primary key,
  period_type_id          text    not null references period_type,   -- "described by"
  from_date               date    not null,
  thru_date               date    not null,   -- exclusive, like every thru_date here
  check (thru_date > from_date)
);

-- OPERATING and CAPITAL BUDGET have no attributes: rows of BUDGET TYPE, as
-- with 8.2's transaction subtypes.
create table budget_type (
  budget_type_id text primary key,   -- OPERATING_BUDGET, CAPITAL_BUDGET
  description    text not null      -- o in the book; every row has one
);

-- The book's budget description is its comment (NOTES, point 18). Whose
-- budget it is lives in budget_role.
create table budget (
  budget_id               integer generated by default as identity primary key,
  budget_type_id          text    not null references budget_type,            -- "described by"
  standard_time_period_id integer not null references standard_time_period,   -- "associated with"
  comment                 text
);

create table budget_item_type (
  budget_item_type_id text primary key,
  description         text not null
);

-- The book keys an item on its budget + seq id (tilde); surrogate key, and
-- the pair unique: one row, one rule. An item may be part of a bigger one;
-- the parent holds the total and the parts add up to it (ours, point 24: a
-- query), so a budget's total is its top items.
create table budget_item (
  budget_item_id         integer generated by default as identity primary key,
  budget_id              integer not null references budget,             -- "part of"
  budget_item_seq_id     integer not null,
  budget_item_type_id    text    not null references budget_item_type,   -- "described by"
  part_of_budget_item_id integer references budget_item,                 -- "part of"
  amount                 numeric not null check (amount >= 0),   -- USD, as first entered (point 22)
  purpose                text,   -- why the item is needed
  justification          text,   -- why this amount
  unique (budget_id, budget_item_seq_id),
  check (part_of_budget_item_id <> budget_item_id)
);

-- BUDGET STATUS: a history, as Ch 4's order status and Ch 7's invoice
-- status. BUDGET STATUS TYPE is a subtype of STATUS TYPE (the text): rows of
-- Ch 2's status_type under a BUDGET_STATUS group, checked by a query.
create table budget_status (
  budget_status_id integer generated by default as identity primary key,
  budget_id        integer not null references budget,        -- "the status for"
  status_type_id   text    not null references status_type,   -- "defined by"
  status_date      date    not null,
  comment          text
);

-- BUDGET ROLE: who is involved in a budget and how (the party it is for, who
-- asked). Its own role-type lookup, like every other role here. No dates
-- drawn.
create table budget_role_type (
  budget_role_type_id text primary key,
  description         text not null
);

create table budget_role (
  budget_role_id      integer generated by default as identity primary key,
  budget_id           integer not null references budget,             -- "involved in"
  party_id            integer not null references party,              -- "for"
  budget_role_type_id text    not null references budget_role_type    -- "for"
);

-- ============================================================
-- Fig 8.7b — Budget revisions: revisions and their impacts
-- ============================================================
-- 8.7a (a whole new budget per revision) is not built (NOTES, point 20).
-- A revision belongs to one budget, numbered within it (the book's "1.1",
-- "1.2" are seq 1 and 2, point 21); the pair unique.
create table budget_revision (
  budget_revision_id integer generated by default as identity primary key,
  budget_id          integer not null references budget,   -- "a revision for"
  revision_seq_id    integer not null,
  date_revised       date    not null,
  unique (budget_id, revision_seq_id)
);

-- The many-to-many between revisions and items, carrying the change.
-- revised_amount is the signed change (−10,000), not the new amount (point
-- 22). ADD marks the revision that created the item (its amount is the
-- item's own, not counted twice); DELETE takes the item to zero. That the
-- item belongs to the revised budget, and stays at or above zero, are
-- queries. One impact per revision and item: the book's key, kept unique.
create table budget_revision_impact (
  budget_revision_impact_id integer generated by default as identity primary key,
  budget_revision_id        integer not null references budget_revision,   -- "from"
  budget_item_id            integer not null references budget_item,       -- "affecting"
  revised_amount            numeric,   -- the change, USD
  add_delete_flag           text check (add_delete_flag in ('ADD', 'DELETE')),
  revision_reason           text,
  unique (budget_revision_id, budget_item_id)
);

-- ============================================================
-- Fig 8.8 — Budget review
-- ============================================================
-- The drawn comment on the result type moves to the review: Table 8.11 gives
-- each review its own (NOTES, point 25).
create table budget_review_result_type (
  budget_review_result_type_id text primary key,   -- ACCEPTED, REJECTED
  description                  text not null
);

-- One party's verdict on a budget on a day. On the budget, not a revision:
-- the reviewer judges the budget as revised so far. That the review comes
-- after the budget was submitted is a query.
create table budget_review (
  budget_review_id             integer generated by default as identity primary key,
  budget_id                    integer not null references budget,                      -- "for"
  party_id                     integer not null references party,                       -- "of": the reviewer
  budget_review_result_type_id text    not null references budget_review_result_type,   -- "described by"
  review_date                  date    not null,
  comment                      text
);

-- ============================================================
-- Fig 8.9 — Budget scenario
-- ============================================================
create table budget_scenario (
  budget_scenario_id integer generated by default as identity primary key,
  description        text not null   -- "poor market conditions", "major deal signed"
);

-- The suggestion: how a scenario usually moves a kind of item. One per
-- scenario and type (the book's key). An amount or a percentage, exactly one
-- (ours, NOTES point 27).
create table budget_scenario_rule (
  budget_scenario_rule_id integer generated by default as identity primary key,
  budget_scenario_id      integer not null references budget_scenario,   -- "for"
  budget_item_type_id     text    not null references budget_item_type,  -- "for"
  amount_change           numeric,   -- USD, signed
  percentage_change       numeric,   -- signed: -15 is 15% less
  unique (budget_scenario_id, budget_item_type_id),
  check (num_nonnulls(amount_change, percentage_change) = 1)
);

-- The decision: what this budget plans under a scenario, for one item or the
-- whole budget (the arc: exactly one, point 28).
create table budget_scenario_application (
  budget_scenario_application_id integer generated by default as identity primary key,
  budget_scenario_id             integer not null references budget_scenario,   -- "from"
  budget_item_id                 integer references budget_item,                -- "affecting"
  budget_id                      integer references budget,                     -- "affecting"
  amount_change                  numeric,
  percentage_change              numeric,
  unique (budget_scenario_id, budget_item_id),
  unique (budget_scenario_id, budget_id),
  check (num_nonnulls(budget_item_id, budget_id) = 1),
  check (num_nonnulls(amount_change, percentage_change) = 1)
);
